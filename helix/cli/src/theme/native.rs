//! `helix theme build --format native`: the theme as a module React Native reads.
//!
//! **The colors the engine derives, and nothing else**, which is what the
//! engine's native module gives a phone that derives at run time
//! (`helix/native/rust`). Written at build time, the same colors reach a phone
//! with no engine in it, such as Expo Go, through `HelixRoot`'s `tokens`.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use fusion_helix_theme::derive::theme::Theme;

/// The module's opening comment.
const HEADER: &str = "/* Generated by `helix theme build --format native` from the theme in helix.json.\n   Do not edit: change the theme there and run it again. */\n";

/// Each color of `theme` by its name after the namespace, in the order a
/// formatter that sorts keys keeps.
fn colors(theme: &Theme) -> BTreeMap<&str, &str> {
    theme
        .tokens
        .iter()
        .map(|token| (token.name.as_str(), token.hex.as_str()))
        .collect()
}

fn block(out: &mut String, mode: &str, theme: &Theme) {
    let _ = writeln!(out, "  {mode}: {{");
    for (name, hex) in colors(theme) {
        let _ = writeln!(out, "    '{name}': '{hex}',");
    }
    out.push_str("  },\n");
}

/// Renders a light and a dark derivation as a TypeScript module exporting
/// `theme`, the shape `HelixRoot`'s `tokens` take: `{ dark, light }`, each a
/// map from a token's name after `--helix-` to its color as sRGB hex.
///
/// **One derivation is both modes**, as `to_css` writes one mode's values
/// for whichever mode the page is in.
#[must_use]
pub fn to_native(light: &Theme, dark: &Theme) -> String {
    let mut out = String::from(HEADER);
    out.push_str("\n/**\n * Each color of the theme in light and dark mode, by its name after `--helix-`,\n * for `HelixRoot`'s `tokens`.\n */\nexport const theme = {\n");
    block(&mut out, "dark", dark);
    block(&mut out, "light", light);
    out.push_str("}\n");
    out
}
