/// The interactions an element holds one style for, each with the GPUI call
/// that sets it.
const INTERACTIONS: &[(&str, &str)] = &[
    ("hover", "hover"),
    ("active", "active"),
    ("focus-visible", "focus_visible"),
];

/// Each module, by its file name, and each element left out, with why.
pub struct Modules {
    pub files: Vec<(String, String)>,
    pub left: Vec<String>,
}

/// The modules for `compiled`, drawn with the tokens of `values`, each
/// naming `source`, the design system's sources.
pub fn modules(compiled: &[Compiled], values: &Values, source: &str) -> Modules {
    let tokens = Tokens::new(values);
    let mut files = Vec::new();
    let mut left = Vec::new();
    let mut written = Vec::new();
    for one in compiled {
        match Element::new(&one.family, &tokens).and_then(|element| element.module(source)) {
            Ok((name, text)) => {
                written.push(name.clone());
                files.push((format!("{name}.rs"), text));
            }
            Err(faults) => left.push(format!("{}: {}", one.element, faults.join("; "))),
        }
    }
    files.push(("theme.rs".to_owned(), theme::module(&tokens, source)));
    let mut index = header(source, &[]);
    index.push_str("pub mod theme;\n");
    for name in &written {
        let _ = writeln!(index, "pub mod {name};");
    }
    files.push(("mod.rs".to_owned(), index));
    Modules { files, left }
}

/// The opening of a module: what wrote it, and what it leaves out.
fn header(source: &str, left: &[String]) -> String {
    let mut out = format!(
        "//! Generated by `{PRODUCT} system gpui` from {source}.\n//! Do not edit: change the source and run it again.\n"
    );
    if !left.is_empty() {
        out.push_str("//!\n//! Left out:\n");
        for one in left {
            let _ = writeln!(out, "//! - {one}");
        }
    }
    out.push_str("#![allow(unused, clippy::all)]\n\n");
    out
}

/// A name as a Rust field: `padding-inline` and `pointerType` are
/// `padding_inline` and `pointer_type`.
pub fn field(name: &str) -> String {
    let mut out = String::new();
    for (index, character) in name.chars().enumerate() {
        if character == '-' {
            out.push('_');
        } else if character.is_ascii_uppercase() {
            if index > 0 {
                out.push('_');
            }
            out.push(character.to_ascii_lowercase());
        } else {
            out.push(character);
        }
    }
    match out.as_str() {
        "type" | "move" | "loop" | "box" | "ref" | "self" | "use" | "where" | "in" | "id"
        | "new" | "hooks" | "children" => format!("{out}_"),
        _ => out,
    }
}

/// A name as a Rust type: `top-start` is `TopStart`.
fn pascal(name: &str) -> String {
    field(name)
        .trim_end_matches('_')
        .split('_')
        .map(|word| {
            let mut characters = word.chars();
            characters.next().map_or_else(String::new, |first| {
                first.to_ascii_uppercase().to_string() + characters.as_str()
            })
        })
        .collect()
}

/// What a prop holds, as the component types it.
enum Kind {
    Flag,
    Words { optional: bool },
    Choice { optional: bool, of: String },
}

/// One element, read for writing.
struct Element<'a> {
    family: &'a Family,
    tokens: &'a Tokens,
    name: String,
    ty: String,
    props: Vec<(&'a Prop, Kind)>,
    hooks: BTreeMap<String, &'static str>,
    left: Vec<String>,
    faults: Vec<String>,
    /// The part the press machine binds, with the event it sends.
    press: Option<(String, String)>,
    /// The lines the render runs before it draws: each eased color.
    prelude: Vec<String>,
}

impl<'a> Element<'a> {
    fn new(family: &'a Family, tokens: &'a Tokens) -> Result<Self, Vec<String>> {
        let name = family
            .tag
            .split_once('-')
            .map_or(family.tag.as_str(), |(_, rest)| rest)
            .to_owned();
        let ty = pascal(&name);
        let mut faults = Vec::new();
        if family.tree.is_empty() {
            faults.push("it has no part tree".to_owned());
        }
        let mut press = None;
        for machine in &family.machines {
            if machine.machine == "press" {
                let part = machine.bind.get("part");
                let sends = machine.bind.get("sends");
                match (part, sends) {
                    (
                        Some(crate::family::ir::machines::Bound::Part(part)),
                        Some(crate::family::ir::machines::Bound::Event(event)),
                    ) => press = Some((part.clone(), event.clone())),
                    _ => faults.push("its press binds no part and event".to_owned()),
                }
            } else {
                faults.push(format!(
                    "it runs `{}`, a later phase's machine",
                    machine.machine
                ));
            }
        }
        if !family.api.states.is_empty() {
            faults.push("it sets custom states, a later phase's".to_owned());
        }
        let mut props = Vec::new();
        for prop in &family.api.props {
            if prop.platform.is_some() {
                continue;
            }
            let optional = prop.default.is_none();
            let kind = match &prop.kind {
                PropType::Primitive(Primitive::Boolean) => Kind::Flag,
                PropType::Primitive(Primitive::String | Primitive::NumberOrString) => {
                    Kind::Words { optional }
                }
                PropType::Values(_) => Kind::Choice {
                    optional,
                    of: format!("{ty}{}", pascal(&prop.name)),
                },
                _ => {
                    faults.push(format!(
                        "its prop `{}` holds a later phase's type",
                        prop.name
                    ));
                    continue;
                }
            };
            props.push((prop, kind));
        }
        if faults.is_empty() {
            Ok(Self {
                family,
                tokens,
                name,
                ty,
                props,
                hooks: BTreeMap::new(),
                left: Vec::new(),
                faults,
                prelude: Vec::new(),
                press,
            })
        } else {
            Err(faults)
        }
    }

    /// The module's file name and text.
    fn module(mut self, source: &str) -> Result<(String, String), Vec<String>> {
        let tree = self.host();
        if !self.faults.is_empty() {
            return Err(self.faults);
        }
        let mut out = header(
            &format!("the `{}` element of {source}", self.family.tag),
            &self.left,
        );
        out.push_str(
            "use std::rc::Rc;\n\n\
             use gpui::prelude::*;\n\
             use gpui::{div, AnyElement, App, ClickEvent, ElementId, Role, SharedString, Window};\n\n\
             use super::theme::ActiveTheme as _;\n\n",
        );
        self.choices(&mut out);
        self.event_types(&mut out);
        self.hooks_type(&mut out);
        self.component(&mut out);
        self.builder(&mut out);
        self.render(&mut out, &tree);
        Ok((field(&self.name), out))
    }

    fn choices(&self, out: &mut String) {
        for (prop, kind) in &self.props {
            let (Kind::Choice { of, .. }, PropType::Values(values)) = (kind, &prop.kind) else {
                continue;
            };
            let _ = writeln!(
                out,
                "/// The values of `{}`.\n#[derive(Clone, Copy, Debug, PartialEq, Eq)]\npub enum {of} {{",
                prop.name
            );
            for value in values {
                let _ = writeln!(out, "    {},", pascal(value));
            }
            out.push_str("}\n\n");
        }
    }

    fn event_types(&self, out: &mut String) {
        for event in &self.family.api.events {
            let _ = writeln!(
                out,
                "/// What `on_{}` hears.\n#[derive(Clone, Debug)]\npub struct {}{}Event {{",
                field(&event.name),
                self.ty,
                pascal(&event.name)
            );
            for detail in &event.detail {
                let _ = writeln!(out, "    pub {}: SharedString,", field(detail));
            }
            out.push_str("}\n\n");
        }
    }

    fn hooks_type(&self, out: &mut String) {
        let _ = writeln!(
            out,
            "/// The values a caller sets over the element's defaults, the web's `--{}-*` custom properties.\n#[derive(Clone, Debug, Default)]\npub struct {}Hooks {{",
            self.family.name, self.ty
        );
        for (hook, ty) in &self.hooks {
            let _ = writeln!(out, "    pub {}: Option<{ty}>,", field(hook));
        }
        out.push_str("}\n\n");
    }

    fn prop_type(kind: &Kind) -> String {
        match kind {
            Kind::Flag => "bool".to_owned(),
            Kind::Words { optional: false } => "SharedString".to_owned(),
            Kind::Words { optional: true } => "Option<SharedString>".to_owned(),
            Kind::Choice {
                optional: false,
                of,
            } => of.clone(),
            Kind::Choice { optional: true, of } => format!("Option<{of}>"),
        }
    }

    fn regions(&self) -> (bool, Vec<String>) {
        let mut default = false;
        let mut named = Vec::new();
        walk(&self.family.tree, &mut |node| {
            if node.kind == NodeKind::Region {
                if node.name == "default" {
                    default = true;
                } else {
                    named.push(node.name.clone());
                }
            }
        });
        (default, named)
    }

    fn component(&self, out: &mut String) {
        let (default, named) = self.regions();
        let _ = writeln!(
            out,
            "/// The `{}` element.\n#[derive(IntoElement)]\npub struct {} {{\n    id: ElementId,",
            self.family.tag, self.ty
        );
        for (prop, kind) in &self.props {
            let _ = writeln!(out, "    {}: {},", field(&prop.name), Self::prop_type(kind));
        }
        let _ = writeln!(out, "    hooks: {}Hooks,", self.ty);
        for event in &self.family.api.events {
            let _ = writeln!(
                out,
                "    on_{}: Option<Rc<dyn Fn(&{}{}Event, &mut Window, &mut App)>>,",
                field(&event.name),
                self.ty,
                pascal(&event.name)
            );
        }
        for region in &named {
            let _ = writeln!(out, "    {}: Option<AnyElement>,", field(region));
        }
        if default {
            out.push_str("    children: Vec<AnyElement>,\n");
        }
        out.push_str("}\n\n");
        if default {
            let _ = writeln!(
                out,
                "impl ParentElement for {} {{\n    fn extend(&mut self, elements: impl IntoIterator<Item = AnyElement>) {{\n        self.children.extend(elements);\n    }}\n}}\n",
                self.ty
            );
        }
    }

    fn builder(&self, out: &mut String) {
        let (default, named) = self.regions();
        let _ = writeln!(
            out,
            "impl {} {{\n    /// The element, known by `id` among the elements around it.\n    pub fn new(id: impl Into<ElementId>) -> Self {{\n        Self {{\n            id: id.into(),",
            self.ty
        );
        for (prop, kind) in &self.props {
            let default_value = match (kind, &prop.default) {
                (Kind::Flag, Some(Literal::Flag(flag))) => flag.to_string(),
                (Kind::Flag, _) => "false".to_owned(),
                (Kind::Words { optional: false }, Some(Literal::Text(text))) => {
                    format!("SharedString::new_static({text:?})")
                }
                (
                    Kind::Choice {
                        optional: false,
                        of,
                    },
                    Some(Literal::Text(text)),
                ) => {
                    format!("{of}::{}", pascal(text))
                }
                _ => "None".to_owned(),
            };
            let _ = writeln!(out, "            {}: {default_value},", field(&prop.name));
        }
        out.push_str("            hooks: Default::default(),\n");
        for event in &self.family.api.events {
            let _ = writeln!(out, "            on_{}: None,", field(&event.name));
        }
        for region in &named {
            let _ = writeln!(out, "            {}: None,", field(region));
        }
        if default {
            out.push_str("            children: Vec::new(),\n");
        }
        out.push_str("        }\n    }\n");
        for (prop, kind) in &self.props {
            let name = field(&prop.name);
            let (argument, value) = match kind {
                Kind::Flag => ("bool".to_owned(), name.clone()),
                Kind::Words { optional } => (
                    "impl Into<SharedString>".to_owned(),
                    if *optional {
                        format!("Some({name}.into())")
                    } else {
                        format!("{name}.into()")
                    },
                ),
                Kind::Choice { optional, of } => (
                    of.clone(),
                    if *optional {
                        format!("Some({name})")
                    } else {
                        name.clone()
                    },
                ),
            };
            let _ = writeln!(
                out,
                "\n    /// Sets `{}`.\n    pub fn {name}(mut self, {name}: {argument}) -> Self {{\n        self.{name} = {value};\n        self\n    }}",
                prop.name
            );
        }
        let _ = writeln!(
            out,
            "\n    /// Sets the values the caller lays over the element's defaults.\n    pub fn hooks(mut self, hooks: {}Hooks) -> Self {{\n        self.hooks = hooks;\n        self\n    }}",
            self.ty
        );
        for event in &self.family.api.events {
            let name = field(&event.name);
            let _ = writeln!(
                out,
                "\n    /// Hears `{}`, the web's `{}` event.\n    pub fn on_{name}(mut self, handler: impl Fn(&{}{}Event, &mut Window, &mut App) + 'static) -> Self {{\n        self.on_{name} = Some(Rc::new(handler));\n        self\n    }}",
                event.name,
                event.name,
                self.ty,
                pascal(&event.name)
            );
        }
        for region in &named {
            let name = field(region);
            let _ = writeln!(
                out,
                "\n    /// Fills the `{region}` region.\n    pub fn {name}(mut self, {name}: impl IntoElement) -> Self {{\n        self.{name} = Some({name}.into_any_element());\n        self\n    }}"
            );
        }
        out.push_str("}\n\n");
    }

    fn render(&self, out: &mut String, tree: &str) {
        let (default, named) = self.regions();
        let mut fields = vec!["id".to_owned()];
        fields.extend(self.props.iter().map(|(prop, _)| field(&prop.name)));
        fields.push("hooks".to_owned());
        fields.extend(
            self.family
                .api
                .events
                .iter()
                .map(|event| format!("on_{}", field(&event.name))),
        );
        fields.extend(named.iter().map(|region| field(region)));
        if default {
            fields.push("children".to_owned());
        }
        let _ = writeln!(
            out,
            "impl RenderOnce for {} {{\n    fn render(self, window: &mut Window, cx: &mut App) -> impl IntoElement {{\n        let {} {{ {} }} = self;\n        let theme = cx.theme().clone();",
            self.ty,
            self.ty,
            fields.join(", ")
        );
        if self.press.is_some() {
            out.push_str(
                "        let focus = window\n            .use_keyed_state(id.clone(), cx, |_, cx| cx.focus_handle())\n            .read(cx)\n            .clone();\n",
            );
        }
        for line in &self.prelude {
            let _ = writeln!(out, "        {line}");
        }
        let _ = writeln!(out, "        {tree}\n    }}\n}}");
    }

    /// The host and the tree inside it, as one expression.
    fn host(&mut self) -> String {
        let mut out = "div()\n            .id(id.clone())".to_owned();
        self.styles("host", None, &mut out, 3);
        let nodes = &self.family.tree;
        for node in nodes {
            self.node(node, &mut out, 3);
        }
        out
    }

    /// `node`, appended to the element expression in `out` as a child.
    fn node(&mut self, node: &'a Node, out: &mut String, depth: usize) {
        let indent = "    ".repeat(depth);
        match node.kind {
            NodeKind::Box | NodeKind::Pressable | NodeKind::Text => {
                let mut child = format!("div()\n{indent}        .id({:?})", node.name);
                self.semantics(node, &mut child, depth + 2);
                self.styles(&node.name, Some(node), &mut child, depth + 2);
                if node.kind == NodeKind::Text {
                    match node.attributes.get("says") {
                        Some(Attribute::Bound(Binding::Bind(prop))) => {
                            let _ =
                                write!(child, "\n{indent}        .child({}.clone())", field(prop));
                        }
                        _ => self.faults.push(format!(
                            "the text `{}` says words a later phase writes",
                            node.name
                        )),
                    }
                }
                for inner in &node.children {
                    self.node(inner, &mut child, depth + 2);
                }
                let _ = write!(out, "\n{indent}.child(\n{indent}    {child}\n{indent})");
            }
            NodeKind::Region => {
                let part = match node.attributes.get("part") {
                    Some(Attribute::Text(part)) => Some(part.clone()),
                    _ => None,
                };
                let content = if node.name == "default" {
                    ".children(children)".to_owned()
                } else {
                    format!(
                        ".when_some({}, |el, child| el.child(child))",
                        field(&node.name)
                    )
                };
                if let Some(part) = part {
                    let mut child = format!("div()\n{indent}        .id({part:?})");
                    self.styles(&part, Some(node), &mut child, depth + 2);
                    let _ = write!(
                        out,
                        "\n{indent}.child(\n{indent}    {child}\n{indent}        {content}\n{indent})"
                    );
                } else {
                    let _ = write!(out, "\n{indent}{content}");
                }
            }
            NodeKind::When => {
                let Some(holds) = self.truthy(&node.name) else {
                    self.faults
                        .push(format!("a `when` reads `{}`, which is no prop", node.name));
                    return;
                };
                let mut inner = "el".to_owned();
                for child in &node.children {
                    self.node(child, &mut inner, depth + 1);
                }
                let _ = write!(
                    out,
                    "\n{indent}.when({holds}, |el| {{\n{indent}    {inner}\n{indent}}})"
                );
            }
            other => self.faults.push(format!(
                "its `{other:?}` node `{}` is a later phase's",
                node.name
            )),
        }
    }

    /// Whether the prop `name` holds, as a Rust expression.
    fn truthy(&self, name: &str) -> Option<String> {
        let (prop, kind) = self.props.iter().find(|(prop, _)| prop.name == name)?;
        let name = field(&prop.name);
        Some(match kind {
            Kind::Flag => name,
            Kind::Words { optional: false } => format!("!{name}.is_empty()"),
            Kind::Words { optional: true } | Kind::Choice { optional: true, .. } => {
                format!("{name}.is_some()")
            }
            Kind::Choice {
                optional: false, ..
            } => "true".to_owned(),
        })
    }

    /// The role, the name, and the press of `node`.
    fn semantics(&mut self, node: &Node, out: &mut String, depth: usize) {
        let indent = "    ".repeat(depth);
        for (name, attribute) in &node.attributes {
            match (name.as_str(), attribute) {
                ("role", Attribute::Text(role)) => match role_name(role) {
                    Some(role) => {
                        let _ = write!(out, "\n{indent}.role(Role::{role})");
                    }
                    None => self
                        .faults
                        .push(format!("the role `{role}` has no GPUI form in the spike")),
                },
                ("label", Attribute::Bound(Binding::Bind(prop))) => {
                    let label = field(prop);
                    let optional = self.props.iter().any(|(one, kind)| {
                        one.name == *prop && matches!(kind, Kind::Words { optional: true })
                    });
                    if optional {
                        let _ = write!(
                            out,
                            "\n{indent}.when_some({label}.clone(), |el, label| el.aria_label(label))"
                        );
                    } else {
                        let _ = write!(
                            out,
                            "\n{indent}.when(!{label}.is_empty(), |el| el.aria_label({label}.clone()))"
                        );
                    }
                }
                ("disabled" | "sends" | "part" | "says", _) => {}
                (other, _) => self.faults.push(format!(
                    "`{}` carries `{other}`, which the spike does not draw",
                    node.name
                )),
            }
        }
        let Some((part, event)) = self.press.clone() else {
            return;
        };
        if part != node.name {
            return;
        }
        let disabled = self
            .attribute_holds(Some(node), "disabled")
            .unwrap_or_else(|| "false".to_owned());
        let detail: Vec<String> = self
            .family
            .api
            .events
            .iter()
            .find(|one| one.name == event)
            .map(|one| one.detail.clone())
            .unwrap_or_default();
        let fields: Vec<String> = detail
            .iter()
            .map(|name| {
                if name == "pointerType" {
                    "pointer_type: SharedString::new_static(match event { ClickEvent::Keyboard(_) => \"keyboard\", ClickEvent::Touch(_) => \"touch\", _ => \"mouse\" })".to_owned()
                } else {
                    format!("{}: SharedString::default()", field(name))
                }
            })
            .collect();
        let _ = write!(
            out,
            "\n{indent}.track_focus(&focus)\n{indent}.tab_stop(!({disabled}))\n{indent}.when_some(on_{}.filter(|_| !({disabled})), |el, handler| {{\n{indent}    el.on_click(move |event, window, cx| {{\n{indent}        handler(&{}{}Event {{ {} }}, window, cx);\n{indent}    }})\n{indent}}})",
            field(&event),
            self.ty,
            pascal(&event),
            fields.join(", ")
        );
    }

    /// Whether `node`'s attribute `name` holds, as a Rust expression.
    fn attribute_holds(&self, node: Option<&Node>, name: &str) -> Option<String> {
        match node?.attributes.get(name)? {
            Attribute::Flag(flag) => Some(flag.to_string()),
            Attribute::Bound(Binding::Bind(prop)) => self.truthy(prop),
            Attribute::Bound(Binding::Not(prop)) => {
                self.truthy(prop).map(|holds| format!("!({holds})"))
            }
            _ => None,
        }
    }

    /// The rules on `target`, appended to the element expression in `out`.
    fn styles(&mut self, target: &str, node: Option<&Node>, out: &mut String, depth: usize) {
        let indent = "    ".repeat(depth);
        let rules: Vec<&Rule> = self
            .family
            .rules
            .iter()
            .filter_map(|item| match item {
                Item::Rule(rule) if rule.target == target && !rule.web_only => Some(rule.as_ref()),
                _ => None,
            })
            .collect();
        /* Each rule's condition, and the interaction it asks for. */
        let mut read = Vec::new();
        for rule in &rules {
            match self.condition(rule, node) {
                Ok(Some(condition)) => read.push((*rule, condition)),
                Ok(None) => {}
                Err(why) => self.faults.push(format!("a rule on `{target}`: {why}")),
            }
        }
        let eased = self.eased(target, &read, out, depth);
        let without = |rule: &Rule| Rule {
            set: rule
                .set
                .iter()
                .filter(|(property, _)| !eased.iter().any(|one| one == property))
                .cloned()
                .collect(),
            ..rule.clone()
        };
        for (rule, (holds, interaction)) in &read {
            if interaction.is_some() {
                continue;
            }
            let calls = self.calls(target, &without(rule));
            if calls.is_empty() {
                continue;
            }
            match holds {
                None => {
                    let _ = write!(out, "\n{indent}{}", calls.join(&format!("\n{indent}")));
                }
                Some(holds) => {
                    let _ = write!(out, "\n{indent}.when({holds}, |el| el{})", calls.join(""));
                }
            }
        }
        for (interaction, call) in INTERACTIONS {
            let Some(first) = read
                .iter()
                .position(|(_, (_, asks))| asks.as_deref() == Some(*interaction))
            else {
                continue;
            };
            let touched: Vec<&str> = read
                .iter()
                .filter(|(_, (_, asks))| asks.as_deref() == Some(*interaction))
                .flat_map(|(rule, _)| rule.set.iter().map(|(property, _)| property.as_str()))
                .collect();
            let mut body = String::new();
            for (rule, (holds, asks)) in &read[first..] {
                if asks.as_deref().is_some_and(|asks| asks != *interaction) {
                    continue;
                }
                let kept = Rule {
                    set: without(rule)
                        .set
                        .into_iter()
                        .filter(|(property, _)| touched.contains(&property.as_str()))
                        .collect(),
                    ..(*rule).clone()
                };
                let calls = self.calls(target, &kept);
                if calls.is_empty() {
                    continue;
                }
                match holds {
                    None => {
                        let _ = write!(body, "\n{indent}    let style = style{};", calls.join(""));
                    }
                    Some(holds) => {
                        let _ = write!(
                            body,
                            "\n{indent}    let style = if {holds} {{ style{} }} else {{ style }};",
                            calls.join("")
                        );
                    }
                }
            }
            if *interaction == "focus-visible"
                && node.is_none_or(|node| node.kind != NodeKind::Pressable)
            {
                self.faults.push(format!(
                    "`{target}` draws a focus ring and takes no focus in the spike"
                ));
            }
            let _ = write!(
                out,
                "\n{indent}.{call}(|style| {{{body}\n{indent}    style\n{indent}}})"
            );
        }
    }

    /// The colors on `target` its unconditional `transition` moves: each one's
    /// rules resolved in order into one value in the render's prelude, eased
    /// by the runtime's driver, and set once in `out`. Returns the properties
    /// it eases, with `transition` among them, which the rules then leave out.
    #[allow(clippy::type_complexity, reason = "the rules as `styles` reads them")]
    fn eased(
        &mut self,
        target: &str,
        read: &[(&Rule, (Option<String>, Option<String>))],
        out: &mut String,
        depth: usize,
    ) -> Vec<String> {
        let declared: Vec<&crate::family::ir::Value> = read
            .iter()
            .filter(|(_, (holds, asks))| holds.is_none() && asks.is_none())
            .flat_map(|(rule, _)| rule.set.iter())
            .filter(|(property, _)| property == "transition")
            .map(|(_, value)| value)
            .collect();
        let [declared] = declared.as_slice() else {
            return Vec::new();
        };
        let reads = Reads {
            tokens: self.tokens,
            hooks: &mut self.hooks,
        };
        let moves = match style::transitions(declared, &reads) {
            Ok(moves) => moves,
            Err(why) => {
                self.left.push(format!("`{target}`: `transition`: {why}"));
                return vec!["transition".to_owned()];
            }
        };
        let indent = "    ".repeat(depth);
        let mut eased = vec!["transition".to_owned()];
        for one in moves {
            let writers: Vec<(&Option<String>, &Option<String>, &crate::family::ir::Value)> = read
                .iter()
                .flat_map(|(rule, (holds, asks))| {
                    rule.set
                        .iter()
                        .filter(|(property, _)| *property == one.property)
                        .map(move |(_, value)| (holds, asks, value))
                })
                .collect();
            if writers.iter().any(|(_, asks, _)| asks.is_some()) {
                self.faults.push(format!(
                    "`{target}`: `{}` changes under an interaction, which the spike does not ease",
                    one.property
                ));
                continue;
            }
            let Some((None, _, _)) = writers.first() else {
                self.faults.push(format!(
                    "`{target}`: the spike eases `{}` from a rule without a condition",
                    one.property
                ));
                continue;
            };
            let name = field(&format!("{target}-{}", one.property));
            let mut resolved = String::new();
            for (holds, _, value) in &writers {
                let mut reads = Reads {
                    tokens: self.tokens,
                    hooks: &mut self.hooks,
                };
                let value = match style::color(value, &mut reads) {
                    Ok(value) => value,
                    Err(why) => {
                        self.faults.push(format!("`{target}`: {why}"));
                        continue;
                    }
                };
                match holds {
                    None => {
                        let _ = write!(resolved, " value = {value};");
                    }
                    Some(holds) => {
                        let _ = write!(resolved, " if {holds} {{ value = {value}; }}");
                    }
                }
            }
            self.prelude.push(format!(
                "let {name} = {{ let mut value; {} value }};",
                resolved.trim_start()
            ));
            self.prelude.push(format!(
                "let {name} = super::theme::eased_color(window, cx, &id, {:?}, {name}, {}, {});",
                format!("{target}-{}", one.property),
                one.duration,
                one.curve
            ));
            if let Some(setter) = style::eased_setter(&one.property) {
                let _ = write!(out, "\n{indent}.{setter}({name})");
            }
            eased.push(one.property);
        }
        eased
    }

    /// The calls of `rule`'s declarations, with each one dropped noted.
    fn calls(&mut self, target: &str, rule: &Rule) -> Vec<String> {
        let mut calls = Vec::new();
        for (property, value) in &rule.set {
            let mut reads = Reads {
                tokens: self.tokens,
                hooks: &mut self.hooks,
            };
            match style::lower(property, value, &mut reads) {
                Ok(Lowered::Calls(more)) => calls.extend(more),
                Ok(Lowered::Dropped(why)) => {
                    let note = format!("`{target}`: {why}");
                    if !self.left.contains(&note) {
                        self.left.push(note);
                    }
                }
                Err(why) => self.faults.push(format!("`{target}`: {why}")),
            }
        }
        calls
    }

    /// When `rule` holds, as a Rust expression, `None` where it always does,
    /// with the interaction it asks for. `Ok(None)` where it never holds on a
    /// desktop window.
    #[allow(
        clippy::type_complexity,
        reason = "a pair read once, beside its reader"
    )]
    fn condition(
        &self,
        rule: &Rule,
        node: Option<&Node>,
    ) -> Result<Option<(Option<String>, Option<String>)>, String> {
        if rule.web_selector() || rule.region.is_some() || rule.slotted.is_some() {
            return Err("it is written with a selector, a region, or slotted children".to_owned());
        }
        let mut terms = Vec::new();
        let mut interaction = None;
        for condition in &rule.when {
            match condition {
                Condition::Attribute { name, value } => {
                    terms.push(self.prop_is(name, value.as_deref())?);
                }
                Condition::Part {
                    name,
                    value,
                    is: None,
                } => {
                    let holds = self
                        .attribute_holds(node, name)
                        .ok_or_else(|| format!("its part carries no `{name}` the spike reads"))?;
                    terms.push(if *value { holds } else { format!("!({holds})") });
                }
                Condition::Disabled { value } => {
                    let holds = self
                        .attribute_holds(node, "disabled")
                        .ok_or_else(|| "its part carries no `disabled`".to_owned())?;
                    terms.push(if *value { holds } else { format!("!({holds})") });
                }
                Condition::Pseudo { names } => match names.as_slice() {
                    [one] if INTERACTIONS.iter().any(|(name, _)| name == one) => {
                        interaction = Some(one.clone());
                    }
                    _ => {
                        return Err(format!(
                            "`{}` is a later phase's interaction",
                            names.join(" ")
                        ))
                    }
                },
                Condition::Media { query }
                    if query == "print" || query == "(forced-colors: active)" =>
                {
                    return Ok(None);
                }
                other => return Err(format!("its condition {other:?} is a later phase's")),
            }
        }
        let holds = if terms.is_empty() {
            None
        } else {
            Some(terms.join(" && "))
        };
        Ok(Some((holds, interaction)))
    }

    /// Whether the prop `name` is `value`, or holds where `value` is `None`.
    fn prop_is(&self, name: &str, value: Option<&str>) -> Result<String, String> {
        let (prop, kind) = self
            .props
            .iter()
            .find(|(prop, _)| prop.name == name)
            .ok_or_else(|| format!("it reads `{name}`, which is no prop the spike draws"))?;
        let field = field(&prop.name);
        match (kind, value) {
            (Kind::Flag, None | Some("" | "true")) => Ok(field),
            (Kind::Choice { optional, of }, Some(value)) => Ok(if *optional {
                format!("{field} == Some({of}::{})", pascal(value))
            } else {
                format!("{field} == {of}::{}", pascal(value))
            }),
            (Kind::Words { optional: true }, None) => Ok(format!("{field}.is_some()")),
            (Kind::Words { optional: false }, Some(value)) => Ok(format!("{field} == {value:?}")),
            _ => Err(format!(
                "it asks `{name}` for a value the spike does not compare"
            )),
        }
    }
}

/// Every node of `nodes`, at any depth.
fn walk<'n>(nodes: &'n [Node], visit: &mut impl FnMut(&'n Node)) {
    for node in nodes {
        visit(node);
        walk(&node.children, visit);
    }
}

/// The AccessKit role of an ARIA role the spike maps.
fn role_name(role: &str) -> Option<&'static str> {
    Some(match role {
        "button" => "Button",
        "status" => "Status",
        "group" => "Group",
        "tab" => "Tab",
        "tablist" => "TabList",
        "tabpanel" => "TabPanel",
        "checkbox" => "CheckBox",
        "switch" => "Switch",
        _ => return None,
    })
}
