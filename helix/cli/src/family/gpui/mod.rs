//! The GPUI components: one Rust module per element, drawn with GPUI, the UI
//! framework of the Zed editor, from the element's intermediate form.
//!
//! **A spike.** `helix/neutral/RUST.md` holds the plan this module tests. It
//! writes the elements whose form needs no more than the spike maps, and
//! names each element it leaves out with why: a machine other than press, a
//! node kind other than a box, a text, a pressable, a region, or a `when`, a
//! condition or a property it has no GPUI form for.
//!
//! **The cascade is worked out here.** Every rule on one target ranks the
//! same, so the later rule wins, and an element's rules are written in source
//! order as conditional style calls, where the later call wins too. GPUI holds
//! one hover style, one active style, and one focus-visible style for each
//! element, so each is one closure. It applies, in order, every rule from the
//! first that asks for that interaction which holds while it does, keeping the
//! properties those rules set, so a later rule without the interaction still
//! wins over an earlier one with it, as on the web.
//!
//! **Each element is a `RenderOnce` component**, as Zed's own `ui` crate
//! writes its components: a struct of its props with a builder method for
//! each, its regions as children, and its events as handlers.

