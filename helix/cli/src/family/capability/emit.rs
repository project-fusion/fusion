//! The TypeScript the contracts are written as: one interface per capability,
//! and one module of the types they share.

use std::any::TypeId;
use std::collections::{BTreeMap, HashSet};
use std::fmt::Write as _;

use ts_rs::{Config, TypeVisitor, TS};

use super::types::{
    Conditions, DragSetup, Dragged, Flag, Frame, Haptic, KeyPress, Point, Rect, Scrolled,
    Transition, Urgency,
};
use super::{Capability, Param, Ty};
use crate::{COMPILER, PRODUCT};

/// The comment each module opens with, naming the contracts it is written
/// from.
fn header() -> String {
    format!(
        "/* Generated by `{PRODUCT} system capabilities` from the contracts in\n   {COMPILER}/capability. Do not edit: change the contract there and\n   run it again. */\n"
    )
}

/// The width a comment wraps at, its markers included.
const WIDTH: usize = 80;

/// One capability's interface, as `<name>/contract.generated.ts`.
pub fn contract(capability: &Capability) -> String {
    let mut named = Vec::new();
    for member in capability.members {
        member.returns.named(&mut named);
        for param in member.params {
            param.ty.named(&mut named);
        }
    }
    named.sort_unstable();
    named.dedup();
    let mut out = format!("{}\n", header());
    if !named.is_empty() {
        let _ = write!(
            out,
            "import type {{ {} }} from '../types.generated.js'\n\n",
            named.join(", ")
        );
    }
    out += &comment(capability.doc, "");
    let generic = if capability.takes_nodes() { "<N>" } else { "" };
    let _ = writeln!(out, "export interface {}{generic} {{", capability.interface);
    for (index, member) in capability.members.iter().enumerate() {
        if index > 0 {
            out.push('\n');
        }
        out += &comment(member.doc, "  ");
        let _ = writeln!(
            out,
            "  readonly {}: ({}) => {}",
            member.name,
            params(member.params),
            ty(member.returns)
        );
    }
    out + "}\n"
}

/// The types the contracts share, as `types.generated.ts`.
pub fn types_module() -> String {
    let config = Config::new();
    let mut declarations = Declarations {
        config: &config,
        found: BTreeMap::new(),
        seen: HashSet::new(),
    };
    declarations.visit::<Conditions>();
    declarations.visit::<DragSetup>();
    declarations.visit::<Dragged>();
    declarations.visit::<Flag>();
    declarations.visit::<Frame>();
    declarations.visit::<Haptic>();
    declarations.visit::<KeyPress>();
    declarations.visit::<Point>();
    declarations.visit::<Rect>();
    declarations.visit::<Scrolled>();
    declarations.visit::<Transition>();
    declarations.visit::<Urgency>();
    declarations.found.insert(
        "Stop".to_owned(),
        "/** Stops what a capability started, such as a timeout or a listener. */\nexport type Stop = () => void".to_owned(),
    );
    let body = declarations
        .found
        .into_values()
        .collect::<Vec<_>>()
        .join("\n\n");
    format!("{}\n{body}\n", header())
}

/// Each declaration the walk reached, by name, as in the intermediate form's
/// types.
struct Declarations<'a> {
    config: &'a Config,
    found: BTreeMap<String, String>,
    seen: HashSet<TypeId>,
}

impl TypeVisitor for Declarations<'_> {
    fn visit<T: TS + 'static + ?Sized>(&mut self) {
        if !self.seen.insert(TypeId::of::<T>()) {
            return;
        }
        if T::output_path().is_some() {
            let docs = T::docs().unwrap_or_default();
            let declaration = T::decl(self.config);
            self.found
                .insert(T::ident(self.config), format!("{docs}export {declaration}"));
        }
        T::visit_dependencies(self);
    }
}

fn params(params: &[Param]) -> String {
    params
        .iter()
        .map(|param| format!("{}: {}", param.name, ty(param.ty)))
        .collect::<Vec<_>>()
        .join(", ")
}

fn ty(ty: Ty) -> String {
    match ty {
        Ty::Boolean => "boolean".to_owned(),
        Ty::Callback(taken, returns) => format!("({}) => {}", params(taken), self::ty(*returns)),
        Ty::List(item) => format!("readonly {}[]", self::ty(*item)),
        Ty::Maybe(item) => format!("{} | null", self::ty(*item)),
        Ty::Named(name) => name.to_owned(),
        Ty::Node => "N".to_owned(),
        Ty::Number => "number".to_owned(),
        Ty::Promise(item) => format!("Promise<{}>", self::ty(*item)),
        Ty::Stop => "Stop".to_owned(),
        Ty::Text => "string".to_owned(),
        Ty::Void => "void".to_owned(),
    }
}

/// A doc comment, on one line where it fits and wrapped where it does not.
fn comment(text: &str, indent: &str) -> String {
    let single = format!("{indent}/** {text} */");
    if single.len() <= WIDTH {
        return single + "\n";
    }
    let mut out = format!("{indent}/**\n");
    let mut line = String::new();
    for word in text.split(' ') {
        if !line.is_empty() && indent.len() + 3 + line.len() + 1 + word.len() > WIDTH {
            let _ = writeln!(out, "{indent} * {line}");
            line.clear();
        }
        if !line.is_empty() {
            line.push(' ');
        }
        line += word;
    }
    out + &format!("{indent} * {line}\n{indent} */\n")
}
