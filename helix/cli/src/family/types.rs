//! The intermediate form's TypeScript types and its JSON Schema, generated
//! from the structs in [`super::ir`] and [`super::api`].
//!
//! **One definition.** The native runtime imports these types and the schema
//! is published beside the form, so a field renamed or added in Rust reaches
//! both in the same change, and `helix system types --check` fails while a
//! written copy is behind.
//!
//! **Every type the form reaches, found by walking it.** The walk starts at
//! [`Family`] and visits each field's type, so a type cannot be left out of the
//! output by a list that forgot it. The declarations are sorted by name, so
//! the output depends on nothing but the types.

use std::any::TypeId;
use std::collections::{BTreeMap, HashSet};

use ts_rs::{Config, TypeVisitor, TS};

use crate::family::ir::{Family, VERSION};
use crate::family::vocabulary::kinds::{Announced, ELEMENTS, ROLES};
use crate::{COMPILER, PRODUCT};

/// Each declaration the walk reached, by name, and every type it visited.
struct Declarations<'a> {
    config: &'a Config,
    found: BTreeMap<String, String>,
    seen: HashSet<TypeId>,
}

impl TypeVisitor for Declarations<'_> {
    fn visit<T: TS + 'static + ?Sized>(&mut self) {
        /* A wrapper such as `Vec<Node>` hands the walk what its item holds,
        not the item, so a recursive type is a cycle the walk breaks by
        remembering each type it has been through. */
        if !self.seen.insert(TypeId::of::<T>()) {
            return;
        }
        /* A type with no file of its own, such as `Vec<Node>`, is written
        inline where it is used. */
        if T::output_path().is_some() {
            let docs = T::docs().unwrap_or_default();
            let declaration = T::decl(self.config);
            self.found
                .insert(T::ident(self.config), format!("{docs}export {declaration}"));
        }
        T::visit_dependencies(self);
    }
}

/// The TypeScript module the native runtime imports.
#[cfg_attr(
    not(feature = "internal"),
    allow(dead_code, reason = "a verb of this repository's builds alone")
)]
pub fn typescript() -> String {
    let config = Config::new().with_large_int("number");
    let mut declarations = Declarations {
        config: &config,
        found: BTreeMap::new(),
        seen: HashSet::new(),
    };
    declarations.visit::<Family>();
    let body = declarations
        .found
        .values()
        .cloned()
        .collect::<Vec<_>>()
        .join("\n\n");
    format!(
        "/* Generated by `{PRODUCT} system types` from the intermediate form's structs in\n   {COMPILER}. Do not edit: change the structs and run it again. */\n\n/** The version of the intermediate form these types describe. */\nexport const VERSION = '{VERSION}'\n\n{body}\n\n{}\n",
        kinds()
    )
}

/// What a phone announces, as the props of a React Native view.
fn announced(native: Announced) -> Vec<String> {
    match native {
        Announced::Trait(name) => vec![format!("accessibilityRole: '{name}'")],
        Announced::Role(name) => vec![format!("role: '{name}'")],
        Announced::Nothing => Vec::new(),
    }
}

/// One entry of an object: its key, quoted where it is not a name, and its
/// fields.
fn entry(name: &str, fields: &[String]) -> String {
    let key = if name.contains('-') {
        format!("'{name}'")
    } else {
        name.to_owned()
    };
    if fields.is_empty() {
        format!("  {key}: {{}},")
    } else {
        format!("  {key}: {{ {} }},", fields.join(", "))
    }
}

/// The roles a node may take and the kinds of element a box may be, from the
/// vocabulary's tables, with what a phone announces for each.
fn kinds() -> String {
    let roles = ROLES
        .iter()
        .map(|role| entry(role.name, &announced(role.native)))
        .collect::<Vec<_>>()
        .join("\n");
    let elements = ELEMENTS
        .iter()
        .map(|element| {
            let mut fields = announced(element.native);
            fields.push(format!("tag: '{}'", element.tag));
            entry(element.name, &fields)
        })
        .collect::<Vec<_>>()
        .join("\n");
    format!(
        "/**\n * Each role a node may take, and what a phone announces for it: React\n * Native's `accessibilityRole`, its `role`, or nothing.\n */\nexport const ROLES = {{\n{roles}\n}} as const\n\n/** A role a node may take. */\nexport type Role = keyof typeof ROLES\n\n/**\n * Each kind of element a box may be: the tag the web draws, `h` and its\n * level for a heading, and what a phone announces for it.\n */\nexport const ELEMENTS = {{\n{elements}\n}} as const\n\n/** A kind of element a box may be. */\nexport type ElementKind = keyof typeof ELEMENTS"
    )
}

/// The JSON Schema of one element's intermediate form.
///
/// # Panics
///
/// Never: a schema is plain JSON.
pub fn schema() -> String {
    let schema = schemars::schema_for!(Family);
    let text = serde_json::to_string_pretty(&schema).expect("a schema serializes");
    format!("{text}\n")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn declares_every_type_the_form_reaches_once() {
        let written = typescript();
        for name in [
            "Family",
            "Api",
            "Node",
            "Attribute",
            "Entry",
            "Rule",
            "Value",
            "Condition",
        ] {
            assert_eq!(
                written.matches(&format!("export type {name} =")).count(),
                1,
                "{name}"
            );
        }
    }

    #[test]
    fn writes_each_role_and_element_with_what_a_phone_announces() {
        let written = typescript();
        assert!(written.contains("  meter: { accessibilityRole: 'progressbar' },"));
        assert!(written.contains("  group: { role: 'group' },"));
        assert!(written.contains("  tabpanel: {},"));
        assert!(written.contains("  'list-item': { role: 'listitem', tag: 'li' },"));
        assert!(written.contains("  passage: { tag: 'blockquote' },"));
        assert!(written.contains("export type Role = keyof typeof ROLES"));
    }

    #[test]
    fn is_the_same_on_every_run() {
        assert_eq!(typescript(), typescript());
        assert_eq!(schema(), schema());
    }
}
