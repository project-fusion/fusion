//! `helix system parts`: the type of the parts each render draws.
//!
//! **Generated rather than inferred.** A `render` is JSX, whose type is one
//! element type whatever it draws, so TypeScript cannot read a part's name out
//! of it. The compiler can, so it writes each element's names as a global
//! interface that `styles()` reads by the element's name, and a style table
//! naming a part its render does not draw fails its typecheck.
//!
//! **Read from the headless source alone.** A misspelled part sits in a style
//! table, and compiling that table would refuse it here, before `tsc` could
//! say where it is.

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};
use std::time::{Duration, SystemTime};

use fusion_rules::error::Failure;

use crate::family::api::{self, Attribute, Headless, Node, NodeKind};
use crate::family::compile;
use crate::family::project::Project;

/// The folder under a package's `src` the types are written into, which is
/// never committed.
const FOLDER: &str = "parts.generated";

/// How long a watch waits between looks at the sources.
const LOOK_EVERY: Duration = Duration::from_millis(500);

/// The regions and the `also` names a tree holds.
fn held(nodes: &[Node], regions: &mut BTreeSet<String>, aliases: &mut BTreeSet<String>) {
    for node in nodes {
        if node.kind == NodeKind::Region {
            regions.insert(node.name.clone());
        }
        if let Some(Attribute::Parts(also)) = node.attributes.get("also") {
            aliases.extend(also.keys().cloned());
        }
        held(&node.children, regions, aliases);
    }
}

/// `'a' | 'b'`, or `never` for no names.
fn union(names: &BTreeSet<String>) -> String {
    if names.is_empty() {
        return "never".to_owned();
    }
    names
        .iter()
        .map(|name| format!("'{name}'"))
        .collect::<Vec<_>>()
        .join(" | ")
}

/// One element's module.
fn module(headless: &Headless, source: &str, command: &str) -> String {
    let mut parts = BTreeSet::new();
    api::parts(&headless.tree, &mut parts);
    let mut regions = BTreeSet::new();
    let mut aliases = BTreeSet::new();
    held(&headless.tree, &mut regions, &mut aliases);
    let mut text = format!("/* Generated by `{command}` from {source}. Do not edit. */\n");
    text.push_str("export {}\n\ndeclare global {\n  interface DrawnParts {\n");
    let _ = writeln!(text, "    '{}': {{", headless.name);
    let _ = writeln!(text, "      readonly aliases: {}", union(&aliases));
    let _ = writeln!(text, "      readonly parts: {}", union(&parts));
    let _ = writeln!(text, "      readonly regions: {}", union(&regions));
    text.push_str("    }\n  }\n}\n");
    text
}

/// The folder the types go into.
fn folder(project: &Project) -> PathBuf {
    project.families.join("src").join(FOLDER)
}

/// Each module to write, by its path.
///
/// # Errors
///
/// [`Failure`] when a headless source cannot be read or compiled.
pub fn outputs(project: &Project, command: &str) -> Result<Vec<(PathBuf, String)>, Failure> {
    let into = folder(project);
    Ok(compile::headless_sources(project)?
        .iter()
        .map(|(element, source, headless)| {
            (
                into.join(format!("{}.d.ts", element.replace('/', "."))),
                module(headless, &project.named(source), command),
            )
        })
        .collect())
}

/// Removes what an element no longer there left behind: its stale name would
/// go on passing a table's check.
///
/// # Errors
///
/// [`Failure`] when a stale module cannot be removed.
pub fn sweep(project: &Project, outputs: &[(PathBuf, String)]) -> Result<(), Failure> {
    let Ok(entries) = fs::read_dir(folder(project)) else {
        return Ok(());
    };
    for path in entries.filter_map(Result::ok).map(|entry| entry.path()) {
        if !outputs.iter().any(|(kept, _)| *kept == path) {
            fs::remove_file(&path).map_err(|error| {
                Failure::input(
                    "cannot remove a stale module",
                    format!("{}: {error}", path.display()),
                )
            })?;
        }
    }
    Ok(())
}

/// The newest change among the headless sources, and how many there are, which
/// tells a watch that one changed, appeared, or went.
fn fingerprint(families: &Path) -> (Option<SystemTime>, usize) {
    let mut newest = None;
    let mut count = 0;
    let folders = |at: &Path| -> Vec<PathBuf> {
        fs::read_dir(at)
            .map(|entries| {
                entries
                    .filter_map(Result::ok)
                    .map(|entry| entry.path())
                    .collect()
            })
            .unwrap_or_default()
    };
    for family in folders(families) {
        for element in folders(&family) {
            let source = element.join("headless.tsx");
            if let Ok(changed) = fs::metadata(&source).and_then(|held| held.modified()) {
                count += 1;
                newest = newest.max(Some(changed));
            }
        }
    }
    (newest, count)
}

/// Runs `write` now and again whenever a headless source changes. A source
/// that does not compile is said and waited out, since it is usually mid-edit.
pub fn watch(project: &Project, mut write: impl FnMut() -> Result<(), Failure>) -> ! {
    let families = project.families.join("src").join("families");
    let mut seen = None;
    loop {
        let now = fingerprint(&families);
        if seen != Some(now) {
            seen = Some(now);
            if let Err(failure) = write() {
                eprintln!("{}", failure.render(crate::PRODUCT));
            }
        }
        std::thread::sleep(LOOK_EVERY);
    }
}

#[cfg(test)]
mod tests {
    use super::module;
    use crate::family::api::{self, rendered};
    use crate::family::read;

    fn headless(source: &str) -> api::Headless {
        let export = read::headless_tsx(source).expect("parses");
        api::headless(&rendered::rewrite(&export).expect("rewrites")).expect("compiles")
    }

    /// A part, a region's part, and an `also` name are all a table's to name,
    /// and a region is not a part.
    #[test]
    fn a_module_names_what_the_render_draws() {
        let written = module(
            &headless(
                r#"
import { headless, Slot, View } from '@fusion.dev/helix-neutral/render'
export default headless('card', {
  render: () => (
    <View part="box" also={{ 'box-wide': true }}>
      <Slot name="title" part="heading" />
    </View>
  ),
})
"#,
            ),
            "src/families/card/root/headless.tsx",
            "helix system parts",
        );
        assert!(written.contains("interface DrawnParts"), "{written}");
        assert!(written.contains("'card': {"), "{written}");
        assert!(
            written.contains("readonly parts: 'box' | 'box-wide' | 'heading'"),
            "{written}"
        );
        assert!(written.contains("readonly regions: 'title'"), "{written}");
        assert!(
            written.contains("readonly aliases: 'box-wide'"),
            "{written}"
        );
    }

    /// A family that draws no regions says so, or a table could name any.
    #[test]
    fn a_kind_with_no_names_is_never() {
        let written = module(
            &headless(
                r#"
import { headless, View } from '@fusion.dev/helix-neutral/render'
export default headless('rule', { render: () => <View part="line" /> })
"#,
            ),
            "x",
            "helix system parts",
        );
        assert!(written.contains("readonly regions: never"), "{written}");
        assert!(written.contains("readonly aliases: never"), "{written}");
    }
}
