/// The design system a token layer is written for: its name, the names it
/// gives its tokens, and the key its own data is kept under in each
/// `$extensions`.
#[derive(Clone, Debug)]
pub struct System {
    pub name: String,
    pub names: Names,
    pub vendor: String,
}

/// The comment a native token module opens with, naming `source`, the file
/// its tokens are read from: a styles package's `tokens.ts`, which reads its
/// primitives, or a Design Tokens Format Module file.
fn header(source: &str, primitives: bool) -> String {
    if primitives {
        format!(
            "/* Generated by `{PRODUCT} system tokens` from {source} and the\n   primitives it reads. Do not edit: change a token there and run it again. */\n"
        )
    } else {
        format!(
            "/* Generated by `{PRODUCT} system tokens` from {source}.\n   Do not edit: change a token there and run it again. */\n"
        )
    }
}

/// The modes a module is written for, with the file and the constant each is
/// written as.
pub const MODES: [(Mode, &str); 2] = [(Mode::Light, "light"), (Mode::Dark, "dark")];

/// Reads `file` under the styles package's `src`.
///
/// # Errors
///
/// [`Failure`] when the file cannot be read.
fn read(styles: &Path, file: &str) -> Result<String, Failure> {
    let path = styles.join("src").join(file);
    fs::read_to_string(&path).map_err(|error| {
        Failure::input(
            "cannot read the token layer",
            format!("{}: {error}", path.display()),
        )
        .hint("name the styles package in the project's `tokens.styles`")
    })
}

/// The custom properties the tokens reach: the primitives, and the modes'
/// defaults.
///
/// # Errors
///
/// [`Failure`] when a stylesheet cannot be read.
pub fn declared(styles: &Path) -> Result<Vec<(String, String)>, Failure> {
    let mut declared = declarations(&read(styles, "primitives.css")?);
    declared.extend(declarations(&read(styles, "_modes.css")?));
    Ok(declared)
}

/// Each token in `tokens.ts` under `styles`, by its name and the builder
/// calls its value is written in.
///
/// # Errors
///
/// [`Failure`] when `tokens.ts` cannot be read, or holds an entry that is not a
/// name and a value.
pub fn written(styles: &Path) -> Result<Vec<(String, Written)>, Failure> {
    Ok(entries(&read(styles, "tokens.ts")?)
        .map_err(|why| Failure::input("cannot read the tokens in tokens.ts", why))?
        .into_iter()
        .map(|(name, value)| (name, Written::Builder(value)))
        .collect())
}

/// The name of each token in `tokens.ts` under `styles`, without its prefix,
/// or `None` where `styles` holds no `tokens.ts`.
///
/// # Errors
///
/// [`Failure`] when `tokens.ts` cannot be read as `TOKENS` entries.
pub fn names(styles: &Path) -> Result<Option<BTreeSet<String>>, Failure> {
    if !styles.join("src").join("tokens.ts").is_file() {
        return Ok(None);
    }
    Ok(Some(
        written(styles)?.into_iter().map(|(name, _)| name).collect(),
    ))
}

/// The name of each token the project's token source holds, without its
/// prefix, or `None` where the project names no source.
///
/// # Errors
///
/// [`Failure`] when the source cannot be read.
pub fn project_names(project: &Project) -> Result<Option<BTreeSet<String>>, Failure> {
    match &project.tokens {
        Tokens::None => Ok(None),
        Tokens::Styles { package, .. } => names(package),
        Tokens::Dtcg { file, .. } => Ok(Some(file::Read::file(file)?.names())),
    }
}

/// The design system `project` describes, with the key its own data is kept
/// under, where the token source names one.
fn system(project: &Project, vendor: Option<&String>) -> System {
    System {
        name: project.name.clone(),
        names: project.names.clone(),
        vendor: vendor.cloned().unwrap_or_default(),
    }
}

/// Writes each mode's native token module, from the project's token source,
/// into the `src/theme` of the package given, or the folder the project's
/// `outputs.tokens` names, or with `--check` says which are behind.
///
/// # Errors
///
/// [`Failure`] when the token layer cannot be read, typed or evaluated, or a
/// module cannot be written.
pub fn native_modules(
    args: &SystemTokens,
    config: Option<&Path>,
    from: &Path,
    json: bool,
) -> Result<Code, Failure> {
    let project = Project::required(config, from)?;
    let root = match &args.package {
        Some(package) => super::locate(package, from).join("src").join("theme"),
        None => project
            .needs(project.outputs.tokens.as_ref(), "outputs.tokens")?
            .to_path_buf(),
    };
    let written = match &project.tokens {
        Tokens::None => {
            return Err(Failure::input(
                format!("{} names no `tokens`", project.file.display()),
                "the native token modules are written from the project's token source",
            ))
        }
        Tokens::Styles { package, vendor } => {
            let source = format!("{}/src/tokens.ts", project.named(package));
            modules(
                &phone_registry(package)?,
                &system(&project, vendor.as_ref()),
                &header(&source, true),
            )?
        }
        Tokens::Dtcg { file, modes } => {
            let read = file::Read::file(file)?;
            let mut source = project.named(file);
            for path in modes.values() {
                source = format!("{source} and {}", project.named(path));
            }
            read.modules(modes, &system(&project, None), &header(&source, false))?
        }
    };
    let outputs: Vec<(PathBuf, String)> = written
        .into_iter()
        .map(|(name, text)| (root.join(name), text))
        .collect();
    output::settle(
        &outputs,
        args.check,
        &format!("{PRODUCT} system tokens"),
        json,
    )
}

/// Writes the Design Tokens Format Module file and its resolver into the
/// styles package's `dist`, or the folder the project's
/// `outputs.designTokens` names, or with `--check` says which are behind.
///
/// # Errors
///
/// [`Failure`] when the token layer cannot be read, typed or evaluated, a
/// token's CSS differs from the CSS `tokens.ts` writes, or a file cannot be
/// written.
#[cfg_attr(
    not(feature = "internal"),
    allow(dead_code, reason = "a verb of this repository's builds alone")
)]
pub fn design_files(
    args: &SystemDesignTokens,
    config: Option<&Path>,
    from: &Path,
    json: bool,
) -> Result<Code, Failure> {
    let project = Project::required(config, from)?;
    let Tokens::Styles { package, vendor } = &project.tokens else {
        return Err(Failure::input(
            "design-tokens writes a styles package's tokens",
            format!(
                "{} names no `tokens.styles`: a `tokens.dtcg` file is in the format already",
                project.file.display()
            ),
        ));
    };
    let vendor = vendor.as_ref().ok_or_else(|| {
        Failure::input(
            format!("{} names no `tokens.vendor`", project.file.display()),
            "each token's own data is written under the vendor's key in `$extensions`",
        )
    })?;
    let styles = args
        .package
        .as_ref()
        .map_or_else(|| package.clone(), |given| super::locate(given, from));
    let dist = match (&args.package, &project.outputs.design_tokens) {
        (None, Some(out)) => out.clone(),
        _ => styles.join("dist"),
    };
    let layer = Layer::read(&styles, system(&project, Some(vendor)))?;
    layer.held_to_stylesheet(&read_built(&styles)?)?;
    let outputs: Vec<(PathBuf, String)> = design_tokens(&layer)?
        .into_iter()
        .map(|(name, text)| (dist.join(name), text))
        .collect();
    output::settle(
        &outputs,
        args.check,
        &format!("{PRODUCT} system design-tokens"),
        json,
    )
}

/// The token layer under `styles` as a phone holds it, which is a coarse
/// pointer: what `pointer: coarse` sets stands over the modes' defaults, as it
/// does on a page on a phone. The design files stay at the defaults.
///
/// # Errors
///
/// [`Failure`] when a source cannot be read, `tokens.ts` holds an entry that is
/// not a name and a value, or a token cannot be typed.
pub fn phone_registry(styles: &Path) -> Result<Registry, Failure> {
    let mut held = declared(styles)?;
    for (name, value) in declared_on_coarse(&read(styles, "_modes.css")?) {
        held.retain(|(known, _)| *known != name);
        held.push((name, value));
    }
    typed(&held, &written(styles)?)
}

/// The tokens `written` typed over `declared`.
///
/// # Errors
///
/// [`Failure`] naming each token that cannot be typed.
pub fn typed(
    declared: &[(String, String)],
    written: &[(String, Written)],
) -> Result<Registry, Failure> {
    Registry::written(declared, written).map_err(|refusals| {
        Failure::input(
            format!("cannot type {} of the token layer's values", refusals.len()),
            refusals.join("\n"),
        )
    })
}

/// `dist/tokens.json` under `styles`, which `turbo run token-layer` writes
/// from what each builder returns.
///
/// # Errors
///
/// [`Failure`] when it has not been built.
fn read_built(styles: &Path) -> Result<String, Failure> {
    let path = styles.join("dist").join("tokens.json");
    fs::read_to_string(&path).map_err(|error| {
        Failure::input(
            "cannot read the CSS the builders wrote",
            format!("{}: {error}", path.display()),
        )
        .hint("run `turbo run token-layer` first")
    })
}

/// Each module, as its file name and its text: one for each mode, and the
/// kinds, which every mode shares. Each opens with `header`.
///
/// # Errors
///
/// [`Failure`] when a token cannot be evaluated in a mode.
pub fn modules(
    registry: &Registry,
    system: &System,
    header: &str,
) -> Result<Vec<(String, String)>, Failure> {
    let mut faults = Vec::new();
    let mut written: Vec<(String, String)> = MODES
        .iter()
        .map(|(mode, name)| {
            let values = registry
                .tokens()
                .iter()
                .filter_map(|token| match registry.evaluate(token, *mode) {
                    Ok(value) => Some((token.name.clone(), native(&value))),
                    Err(why) => {
                        faults.push(why);
                        None
                    }
                })
                .collect::<Vec<_>>();
            (
                format!("{name}.generated.ts"),
                module(system, header, name, &values),
            )
        })
        .collect();
    let kinds: Vec<(String, &str)> = registry
        .tokens()
        .iter()
        .map(|token| (token.name.clone(), kind_name(token.kind)))
        .collect();
    written.push((
        "kinds.generated.ts".to_owned(),
        kinds_module(system, header, &kinds),
    ));
    if faults.is_empty() {
        Ok(written)
    } else {
        Err(Failure::input(
            format!("cannot evaluate {} of the token values", faults.len()),
            faults.join("\n"),
        ))
    }
}

/// One mode's module: each token's value, as the native theme takes it.
fn module(system: &System, header: &str, name: &str, values: &[(String, Native)]) -> String {
    let mut out = format!(
        "{header}\n/**\n * Each {} token's value in {name} mode, by its name after `{}`, as the\n * native theme takes it: a color as sRGB hex, a length in pixels as points, a\n * length in rems or ems as the CSS it is written in, and a duration in\n * milliseconds. The theme draws a rem at 16 points times the reader's text size.\n */\nexport const {name} = {{\n",
        system.name,
        system.names.token("")
    );
    for (token, value) in values {
        let written = match value {
            Native::Number(number) => format!("{number}"),
            Native::Text(text) => quoted(text),
        };
        let _ = writeln!(out, "  {}: {written},", quoted(token));
    }
    out + "} as const satisfies Readonly<Record<string, number | string>>\n"
}

/// The name a kind is written as.
fn kind_name(kind: Kind) -> &'static str {
    match kind {
        Kind::Color => "color",
        Kind::Easing => "easing",
        Kind::Family => "family",
        Kind::Filter => "filter",
        Kind::Length => "length",
        Kind::Number => "number",
        Kind::Shadow => "shadow",
        Kind::Time => "time",
    }
}

/// The module of kinds: what each token holds, which is the same in every
/// mode, so a reader tells a length in points from a plain number.
fn kinds_module(system: &System, header: &str, kinds: &[(String, &str)]) -> String {
    let mut out = format!(
        "{header}\n/**\n * What each {} token holds, by its name after `{}`, the same in every\n * mode. A length's value is points, or a string in rems or ems, and a time's\n * is milliseconds, where a number's is the number itself, so a reader tells\n * them apart by its kind.\n */\nexport const kinds = {{\n",
        system.name,
        system.names.token("")
    );
    for (token, kind) in kinds {
        let _ = writeln!(out, "  {}: {},", quoted(token), quoted(kind));
    }
    out + "} as const satisfies Readonly<\n  Record<string, 'color' | 'easing' | 'family' | 'filter' | 'length' | 'number' | 'shadow' | 'time'>\n>\n"
}

/// `text` as a single-quoted TypeScript string.
fn quoted(text: &str) -> String {
    format!("'{}'", text.replace('\\', "\\\\").replace('\'', "\\'"))
}

/// Each `[name, value, description?]` entry of the `TOKENS` that `source`
/// exports, as its name and the source text of its value.
///
/// # Errors
///
/// A sentence when the module does not parse, exports no `TOKENS` array, or
/// holds an entry that does not open with a quoted name and a value.
pub fn entries(source: &str) -> Result<Vec<(String, String)>, String> {
    let allocator = Allocator::default();
    let parsed = Parser::new(&allocator, source, SourceType::ts()).parse();
    if let Some(error) = parsed.diagnostics.first() {
        return Err(format!("tokens.ts does not parse: {error}"));
    }
    let array = parsed
        .program
        .body
        .iter()
        .filter_map(|statement| match statement {
            Statement::ExportDeclaration(export) => match &export.declaration {
                Declaration::VariableDeclaration(declaration) => Some(&declaration.declarations),
                _ => None,
            },
            _ => None,
        })
        .flatten()
        .find(|declarator| declarator.id.get_identifier_name().as_deref() == Some("TOKENS"))
        .and_then(|declarator| match &declarator.init {
            Some(Expression::ArrayExpression(array)) => Some(array),
            _ => None,
        })
        .ok_or_else(|| "tokens.ts exports no `TOKENS` array".to_owned())?;
    array
        .elements
        .iter()
        .enumerate()
        .map(|(at, element)| {
            let entry = match element.as_expression() {
                Some(Expression::ArrayExpression(entry)) => Some(entry),
                _ => None,
            };
            let parts: Vec<&Expression> = entry
                .map(|entry| {
                    entry
                        .elements
                        .iter()
                        .filter_map(|one| one.as_expression())
                        .collect()
                })
                .unwrap_or_default();
            match parts.as_slice() {
                [Expression::StringLiteral(name), value, ..] => {
                    let span = value.span();
                    let text = &source[span.start as usize..span.end as usize];
                    Ok((name.value.display().to_string(), text.to_owned()))
                }
                _ => Err(format!(
                    "entry {} of `TOKENS` does not open with a name and a value",
                    at + 1
                )),
            }
        })
        .collect()
}
