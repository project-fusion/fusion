const HEADER: &str = "/* Generated by `helix family tokens` from helix/styles/src/tokens.ts and the\n   primitives it reads. Do not edit: change a token there and run it again. */\n";

/// The modes a module is written for, with the file and the constant each is
/// written as.
pub const MODES: [(Mode, &str); 2] = [(Mode::Light, "light"), (Mode::Dark, "dark")];

/// Reads `file` under the styles package's `src`.
///
/// # Errors
///
/// [`Failure`] when the file cannot be read.
fn read(styles: &Path, file: &str) -> Result<String, Failure> {
    let path = styles.join("src").join(file);
    fs::read_to_string(&path).map_err(|error| {
        Failure::input(
            "cannot read the token layer",
            format!("{}: {error}", path.display()),
        )
        .hint("pass a package beside helix/styles, such as helix/native")
    })
}

/// The custom properties the tokens reach: the primitives, and the modes'
/// defaults.
///
/// # Errors
///
/// [`Failure`] when a stylesheet cannot be read.
pub fn declared(styles: &Path) -> Result<Vec<(String, String)>, Failure> {
    let mut declared = declarations(&read(styles, "primitives.css")?);
    declared.extend(declarations(&read(styles, "_modes.css")?));
    Ok(declared)
}

/// Each token in `tokens.ts` under `styles`, by its name and the builder
/// calls its value is written in.
///
/// # Errors
///
/// [`Failure`] when `tokens.ts` cannot be read, or holds an entry that is not a
/// name and a value.
pub fn written(styles: &Path) -> Result<Vec<(String, Written)>, Failure> {
    Ok(entries(&read(styles, "tokens.ts")?)
        .map_err(|why| Failure::input("cannot read the tokens in tokens.ts", why))?
        .into_iter()
        .map(|(name, value)| (name, Written::Builder(value)))
        .collect())
}

/// The name of each token in `tokens.ts` under `styles`, without `--helix-`,
/// or `None` where `styles` holds no `tokens.ts`.
///
/// # Errors
///
/// [`Failure`] when `tokens.ts` cannot be read as `TOKENS` entries.
pub fn names(styles: &Path) -> Result<Option<BTreeSet<String>>, Failure> {
    if !styles.join("src").join("tokens.ts").is_file() {
        return Ok(None);
    }
    Ok(Some(
        written(styles)?.into_iter().map(|(name, _)| name).collect(),
    ))
}

/// The token layer under `styles`, typed.
///
/// # Errors
///
/// [`Failure`] when a source cannot be read, `tokens.ts` holds an entry that is
/// not a name and a value, or a token cannot be typed.
pub fn registry(styles: &Path) -> Result<Registry, Failure> {
    typed(&declared(styles)?, &written(styles)?)
}

/// The tokens `written` typed over `declared`.
///
/// # Errors
///
/// [`Failure`] naming each token that cannot be typed.
pub fn typed(
    declared: &[(String, String)],
    written: &[(String, Written)],
) -> Result<Registry, Failure> {
    Registry::written(declared, written).map_err(|refusals| {
        Failure::input(
            format!("cannot type {} of the token layer's values", refusals.len()),
            refusals.join("\n"),
        )
    })
}

/// Writes each mode's native token module under the package's `src/theme`,
/// from the token layer in the styles package beside it, or with `--check`
/// says which are behind.
///
/// # Errors
///
/// [`Failure`] when the token layer cannot be read, typed or evaluated, or a
/// module cannot be written.
pub fn native_modules(args: &FamilyTokens, from: &Path, json: bool) -> Result<Code, Failure> {
    let package = super::locate(&args.package, from);
    let styles = package.parent().unwrap_or(&package).join("styles");
    let root = package.join("src").join("theme");
    let outputs: Vec<(PathBuf, String)> = modules(&registry(&styles)?)?
        .into_iter()
        .map(|(name, text)| (root.join(name), text))
        .collect();
    output::settle(&outputs, args.check, "helix family tokens", json)
}

/// Writes the Design Tokens Format Module file and its resolver into the
/// styles package's `dist`, or with `--check` says which are behind.
///
/// # Errors
///
/// [`Failure`] when the token layer cannot be read, typed or evaluated, a
/// token's CSS differs from the CSS `tokens.ts` writes, or a file cannot be
/// written.
pub fn design_files(args: &FamilyDesignTokens, from: &Path, json: bool) -> Result<Code, Failure> {
    let styles = super::locate(&args.package, from);
    let layer = Layer::read(&styles)?;
    layer.held_to_stylesheet(&read_built(&styles)?)?;
    let dist = styles.join("dist");
    let outputs: Vec<(PathBuf, String)> = design_tokens(&layer)?
        .into_iter()
        .map(|(name, text)| (dist.join(name), text))
        .collect();
    output::settle(&outputs, args.check, "helix family design-tokens", json)
}

/// `dist/tokens.json` under `styles`, which `turbo run token-layer` writes
/// from what each builder returns.
///
/// # Errors
///
/// [`Failure`] when it has not been built.
fn read_built(styles: &Path) -> Result<String, Failure> {
    let path = styles.join("dist").join("tokens.json");
    fs::read_to_string(&path).map_err(|error| {
        Failure::input(
            "cannot read the CSS the builders wrote",
            format!("{}: {error}", path.display()),
        )
        .hint("run `turbo run token-layer` first")
    })
}

/// Each module, as its file name and its text: one for each mode, and the
/// kinds, which every mode shares.
///
/// # Errors
///
/// [`Failure`] when a token cannot be evaluated in a mode.
pub fn modules(registry: &Registry) -> Result<Vec<(String, String)>, Failure> {
    let mut faults = Vec::new();
    let mut written: Vec<(String, String)> = MODES
        .iter()
        .map(|(mode, name)| {
            (
                format!("{name}.generated.ts"),
                module(registry, *mode, name, &mut faults),
            )
        })
        .collect();
    written.push(("kinds.generated.ts".to_owned(), kinds(registry)));
    if faults.is_empty() {
        Ok(written)
    } else {
        Err(Failure::input(
            format!("cannot evaluate {} of the token values", faults.len()),
            faults.join("\n"),
        ))
    }
}

/// One mode's module, noting in `faults` each token it cannot evaluate.
fn module(registry: &Registry, mode: Mode, name: &str, faults: &mut Vec<String>) -> String {
    let mut out = format!(
        "{HEADER}\n/**\n * Each Helix token's value in {name} mode, by its name after `--helix-`, as the\n * native theme takes it: a color as sRGB hex, a length in pixels as points, a\n * length in rems or ems as the CSS it is written in, and a duration in\n * milliseconds. The theme draws a rem at 16 points times the reader's text size.\n */\nexport const {name} = {{\n"
    );
    for token in registry.tokens() {
        match registry.evaluate(token, mode) {
            Ok(value) => {
                let written = match native(&value) {
                    Native::Number(number) => format!("{number}"),
                    Native::Text(text) => quoted(&text),
                };
                let _ = writeln!(out, "  {}: {written},", quoted(&token.name));
            }
            Err(why) => faults.push(why),
        }
    }
    out + "} as const satisfies Readonly<Record<string, number | string>>\n"
}

/// The name a kind is written as.
fn kind_name(kind: Kind) -> &'static str {
    match kind {
        Kind::Color => "color",
        Kind::Easing => "easing",
        Kind::Family => "family",
        Kind::Filter => "filter",
        Kind::Length => "length",
        Kind::Number => "number",
        Kind::Shadow => "shadow",
        Kind::Time => "time",
    }
}

/// The module of kinds: what each token holds, which is the same in every
/// mode, so a reader tells a length in points from a plain number.
fn kinds(registry: &Registry) -> String {
    let mut out = format!(
        "{HEADER}\n/**\n * What each Helix token holds, by its name after `--helix-`, the same in every\n * mode. A length's value is points, or a string in rems or ems, and a time's\n * is milliseconds, where a number's is the number itself, so a reader tells\n * them apart by its kind.\n */\nexport const kinds = {{\n"
    );
    for token in registry.tokens() {
        let _ = writeln!(
            out,
            "  {}: {},",
            quoted(&token.name),
            quoted(kind_name(token.kind))
        );
    }
    out + "} as const satisfies Readonly<\n  Record<string, 'color' | 'easing' | 'family' | 'filter' | 'length' | 'number' | 'shadow' | 'time'>\n>\n"
}

/// `text` as a single-quoted TypeScript string.
fn quoted(text: &str) -> String {
    format!("'{}'", text.replace('\\', "\\\\").replace('\'', "\\'"))
}

/// Each `[name, value, description?]` entry of the `TOKENS` that `source`
/// exports, as its name and the source text of its value.
///
/// # Errors
///
/// A sentence when the module does not parse, exports no `TOKENS` array, or
/// holds an entry that does not open with a quoted name and a value.
pub fn entries(source: &str) -> Result<Vec<(String, String)>, String> {
    let allocator = Allocator::default();
    let parsed = Parser::new(&allocator, source, SourceType::ts()).parse();
    if let Some(error) = parsed.diagnostics.first() {
        return Err(format!("tokens.ts does not parse: {error}"));
    }
    let array = parsed
        .program
        .body
        .iter()
        .filter_map(|statement| match statement {
            Statement::ExportDeclaration(export) => match &export.declaration {
                Declaration::VariableDeclaration(declaration) => Some(&declaration.declarations),
                _ => None,
            },
            _ => None,
        })
        .flatten()
        .find(|declarator| declarator.id.get_identifier_name().as_deref() == Some("TOKENS"))
        .and_then(|declarator| match &declarator.init {
            Some(Expression::ArrayExpression(array)) => Some(array),
            _ => None,
        })
        .ok_or_else(|| "tokens.ts exports no `TOKENS` array".to_owned())?;
    array
        .elements
        .iter()
        .enumerate()
        .map(|(at, element)| {
            let entry = match element.as_expression() {
                Some(Expression::ArrayExpression(entry)) => Some(entry),
                _ => None,
            };
            let parts: Vec<&Expression> = entry
                .map(|entry| {
                    entry
                        .elements
                        .iter()
                        .filter_map(|one| one.as_expression())
                        .collect()
                })
                .unwrap_or_default();
            match parts.as_slice() {
                [Expression::StringLiteral(name), value, ..] => {
                    let span = value.span();
                    let text = &source[span.start as usize..span.end as usize];
                    Ok((name.value.to_string(), text.to_owned()))
                }
                _ => Err(format!(
                    "entry {} of `TOKENS` does not open with a name and a value",
                    at + 1
                )),
            }
        })
        .collect()
}
