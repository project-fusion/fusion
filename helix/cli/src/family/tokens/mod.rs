//! The token layer's outputs that are written from its typed expressions: the
//! native modules, one per mode, and the Design Tokens Format Module file.
//!
//! **Read from the token layer's own source.** `helix/styles/src/tokens.ts`
//! is read as syntax for its `TOKENS` entries, each value a call to a typed
//! builder, and `primitives.css` and `_modes.css` for the custom properties
//! the tokens reach. `fusion-helix-theme` types each value, refuses one it
//! cannot type or that does not print back as written, and evaluates the rest
//! per mode, so a token the grammar does not admit stops the write with its
//! name.
//!
//! **What a value becomes natively is `fusion_helix_theme::tokens::native`'s
//! to say**: a color as sRGB hex, a length in pixels as points, a length in
//! rems or ems as the CSS it is written in, and a duration in milliseconds.

