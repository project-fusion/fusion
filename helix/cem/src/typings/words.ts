import type { HelixManifest } from '../types.js'

/** A family's word properties, under the key its words register with. */
type Families = Map<string, Map<string, { description: string; english: string; table: boolean }>>

/** The first paragraph of a description, which is what a translator needs. */
const lead = (description: string): string => description.split(/\n\s*\n/)[0]?.trim() ?? ''

/** A string literal's text, or the source as written where it is something else. */
const unquoted = (written: string): string =>
  /^(['"`]).*\1$/s.test(written) ? written.slice(1, -1) : written

/**
 * Every family's word properties in a manifest.
 *
 * **Keyed by the class's static `words`**, the family's styled tag, so the
 * headless and styled manifests give one key each family, and a member is
 * taken where any class in the manifest declares it.
 */
export const wordsOf = (manifest: HelixManifest): Families => {
  const families: Families = new Map()
  for (const unit of manifest.modules ?? []) {
    for (const declaration of unit.declarations ?? []) {
      const members = declaration.members ?? []
      const key = members.find((one) => one.static && one.name === 'words')?.default
      if (!key) {
        continue
      }
      const into = families.get(unquoted(key)) ?? new Map()
      families.set(unquoted(key), into)
      for (const member of members) {
        if (!member.helix?.words || into.has(member.name)) {
          continue
        }
        into.set(member.name, {
          description: lead(member.description ?? ''),
          english: unquoted(member.default ?? ''),
          table: /Record|\{/.test(member.type?.text ?? ''),
        })
      }
    }
  }
  return families
}

/** A doc block's text, with nothing that would close the block early. */
const safe = (text: string): string => text.replaceAll('*/', '*\\/')

/**
 * `words.d.ts`, which types `registerWords` from the manifest: one member of
 * `HelixWords` per family, holding its word properties, each with its
 * description and its English.
 *
 * **An augmentation of core's empty interface**, the way an element of your
 * own adds its words, so a typo in a tag's property is a type error and a tag
 * the interface does not name still takes any words.
 *
 * **The registry is re-exported here**, so the entry this file types is a
 * module of its own: `import { registerWords } from '@fusion.dev/helix/words'`
 * costs the registry and nothing else, and the call is typed against the
 * package's families in the same import. Without it the entry was types alone,
 * and the function came from the package's index, which registers every
 * element.
 */
export const renderWords = (families: Families, packageName?: string): string => {
  const lines = [
    "// Generated by `helix-cem` from this package's manifest. Do not edit.",
    '//',
    '// `registerWords`, and the words each family lets you register with it, keyed',
    ...(packageName
      ? [
          '// by the family tag. Import it from here, which types your calls:',
          `// \`import { registerWords } from '${packageName}/words'\`. With it imported`,
          `// from elsewhere, \`import type {} from '${packageName}/words'\` types them.`,
        ]
      : ['// by the family tag. Import it from here, which types your calls.']),
    "import type { Message, MessageTable } from '@fusion.dev/helix-core'",
    '',
    "export * from '@fusion.dev/helix-core/words'",
    '',
    "declare module '@fusion.dev/helix-core' {",
    '  interface HelixWords {',
  ]
  for (const [key, members] of [...families].sort(([a], [b]) => a.localeCompare(b))) {
    lines.push(`    '${key}': {`)
    for (const [name, { description, english, table }] of [...members].sort(([a], [b]) =>
      a.localeCompare(b),
    )) {
      lines.push(
        '      /**',
        ...safe(description)
          .split('\n')
          .map((line) => `       * ${line.trim()}`.trimEnd()),
        '       *',
        `       * English: \`${safe(english)}\``,
        '       */',
        `      ${name}: ${table ? 'MessageTable' : 'Message'}`,
      )
    }
    lines.push('    }')
  }
  lines.push('  }', '}', '')
  return lines.join('\n')
}
