import type { HelixManifest } from '../types.js'
import {
  comment,
  customCssProperties,
  descriptionDoc,
  type Element,
  elementsOf,
  eventAliases,
  importLine,
  lead,
  NUMERIC_STRING,
  TYPED_EVENT,
} from './elements.js'

/** Vue's own types, and the shape it reads a custom element's template types through. */
const HEAD = `import type { HTMLAttributes, PublicProps, EmitFn, EmitsToProps } from "vue";

${TYPED_EVENT}
export type EventMap = {
  [event: string]: Event;
};

// Vue's template type-checking reads props from $props and events from $emit.
// See: https://vuejs.org/guide/extras/web-components.html#non-vue-web-components-and-typescript
export type VueEmitsOptions<T extends EventMap> = {
  [K in keyof T]: (event: T[K]) => void;
};

export type VueEmit<T extends EventMap> = EmitFn<VueEmitsOptions<T>>;

// Helps Volar autocomplete "@event" by providing "onXxx" props.
export type VueOnProps<T extends EventMap> = EmitsToProps<VueEmitsOptions<T>>;

export type DefineCustomElement<
  ElementType extends HTMLElement,
  Props = {},
  Events extends EventMap = {},
> = new () => ElementType & {
  /** @deprecated Do not use the $props property on a Custom Element ref; this is for template prop types only. */
  $props: HTMLAttributes & Props & PublicProps & VueOnProps<Events>;

  /** @deprecated Do not use the $emit property on a Custom Element ref; this is for template event types only. */
  $emit: VueEmit<Events>;
};
`

/** Where each tag is declared, and the attribute Vue's own types leave out. */
const TAIL = `declare module "@vue/runtime-core" {
  interface GlobalComponents extends HelixVueGlobalComponents {}
}

declare module "@vue/runtime-dom" {
  interface GlobalComponents extends HelixVueGlobalComponents {}

  // Needed for named slots on native elements when using Web Components.
  // Vue templates otherwise reject: <span slot="icon" />
  interface HTMLAttributes {
    slot?: string | undefined;
  }
}

declare module "vue" {
  interface GlobalComponents extends HelixVueGlobalComponents {}

  // Some package managers (notably pnpm) may not make "@vue/runtime-dom" directly
  // resolvable from the consuming project, so we also augment via "vue".
  interface HTMLAttributes {
    slot?: string | undefined;
  }

  interface CSSProperties extends CustomCssProperties {}
}
`

/**
 * The props one tag declares, and its events.
 *
 * **A numeric attribute's property takes the string as well, and only in Vue.**
 * `vue-tsc` reads a kebab attribute that has a value as its camelCase property,
 * so `default-page="2"` is checked against `defaultPage`, and the kebab entry is
 * read only for an attribute with no value, such as `line-numbers`. At runtime
 * Vue finds no `default-page` on the element and writes the attribute, whose
 * converter reads the number out of it. The price is that `defaultPage="2"`
 * compiles too, which Vue assigns as a string, because the checker sees the two
 * spellings as one. `default-page="abc"` is still refused.
 */
const vueTypes = ({ events, name, props }: Element): string => {
  const written = new Set<string>()
  const lines: string[] = []
  const entry = (key: string, doc: string, type: string): void => {
    if (!written.has(key)) {
      written.add(key)
      lines.push(`${comment(doc, '  ')}  "${key}"?: ${type};\n`)
    }
  }
  for (const { attribute, doc, numeric, property, type } of props) {
    const full = `${type}${numeric ? ` | ${NUMERIC_STRING}` : ''} | undefined`
    if (attribute !== undefined && attribute !== property) {
      entry(attribute, doc, full)
    }
    if (property !== undefined) {
      entry(property, attribute !== undefined && attribute !== property ? lead(doc) : doc, full)
    }
  }
  const handlers = events
    .map(({ doc, handler, name: event }) => `${comment(doc, '  ')}  "${event}": ${handler};\n`)
    .join('')
  return `export type ${name}VueProps = {
${lines.join('')}};

export type ${name}VueEvents = {
${handlers}};
`
}

/**
 * `vue.d.ts`: the tags for Vue templates, written from the manifest.
 *
 * **Vue reads none of the JSX file.** Its templates are not JSX, so the types
 * augment `GlobalComponents`, and you bind a handler with `@helix-input`.
 */
export const renderVue = (manifest: HelixManifest, packageName: string): string => {
  const elements = elementsOf(manifest)
  return [
    "// Generated by `helix-cem` from this package's manifest. Do not edit.\n",
    importLine(elements, packageName),
    HEAD,
    ...elements.flatMap((element) => [eventAliases(element), vueTypes(element)]),
    customCssProperties(elements),
    `// Vue SFC template type-checking (GlobalComponents) for non-Vue custom elements.
// Some tooling expects this augmentation under "@vue/runtime-core", while other
// docs and examples use "vue", so it is written under both.
export interface HelixVueGlobalComponents {
${elements
  .map(
    (element) =>
      `${descriptionDoc(element, '  ')}  "${element.tagName}": DefineCustomElement<${element.name}, ${element.name}VueProps, ${element.name}VueEvents>;\n`,
  )
  .join('')}}
`,
    TAIL,
  ].join('\n')
}
