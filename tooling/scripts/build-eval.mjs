#!/usr/bin/env node
/**
 * Builds the agent evaluation corpus out of the artifacts that are already
 * checked.
 *
 * **Nothing agent-facing ships without an eval, and this is the half that can be
 * built rather than judged.** A skill or an MCP server would be the first thing
 * this repository publishes whose output is not deterministic: everything else is
 * held by a check comparing bytes or counting assertions, and an agent answers
 * the same question differently on two runs. So a green `verify` would say
 * nothing about whether the thing helps, and the failure mode is not a red build
 * but a confident wrong answer.
 *
 * **The questions are generated, never written.** A hand-written corpus goes
 * stale the first time a family is renamed and nothing says so, which is the
 * exact failure the documentation read of 24 Aug 2026 found nine of. Every
 * question here is derived from the manifest, the token set or the example
 * index, so a rename either updates a question or fails `check:eval`.
 *
 * **What it deliberately does not contain is a question about prose.** "Explain
 * why raised goes down the ramp" has no machine-comparable answer, and a corpus
 * that mixed those in would have a score nobody could act on. The four kinds
 * below all have exactly one right answer that a current artifact states.
 *
 * Run with `bun run eval:build`; `check:eval` holds the result.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const OUT = join(ROOT, 'tooling', 'eval', 'questions.json')

/**
 * The family a declaration belongs to.
 *
 * **`.at(-3)` and not `.at(-2)`, which is a correction rather than a choice.**
 * A `modulePath` is `src/<family>/<part>/<file>.ts`, so the second-from-last
 * segment is the *part*: `helix-accordion-item` came out as `item` and twelve
 * families in the corpus were named after a part. The eval scored 100% anyway,
 * because the reference read the path the same wrong way the generator did.
 *
 * That is the one failure a self-checking corpus cannot see, so it is guarded
 * from outside rather than by agreement: every family named in the corpus has to
 * be a directory under `helix/styled/src` with an `index.ts`, which is the same test
 * `check:examples` uses to decide what a family is.
 */
const familyOf = (declaration) => declaration.modulePath?.split('/').at(-3) ?? declaration.tagName

/** Every tagged declaration in the styled manifest, with its Helix metadata. */
const families = () => {
  const manifest = JSON.parse(
    readFileSync(join(ROOT, 'helix', 'styled', 'custom-elements.json'), 'utf8'),
  )
  const found = []
  for (const module of manifest.modules ?? []) {
    for (const declaration of module.declarations ?? []) {
      if (!declaration.tagName || !declaration.helix) {
        continue
      }
      found.push({
        aliases: declaration.helix.aliases ?? [],
        category: declaration.helix.category,
        events: (declaration.events ?? []).map((event) => event.name),
        examples: declaration.helix.examples ?? [],
        family: familyOf(declaration),
        hooks: (declaration.cssProperties ?? []).map((hook) => hook.name),
        parts: (declaration.cssParts ?? []).map((part) => part.name),
        summary: declaration.summary,
        tag: declaration.tagName,
      })
    }
  }
  return found
}

const tokens = () =>
  JSON.parse(readFileSync(join(ROOT, 'helix', 'styles', 'tokens.json'), 'utf8')).tokens.map(
    (token) => token.name,
  )

/**
 * A name that is not a token but looks exactly like one.
 *
 * **Generated by mutating a real name rather than invented**, because the
 * question worth asking is not "is `--nonsense` a token" but "is
 * `--helix-color-border-subtle` a token", which is the shape an agent produces
 * when it is pattern-matching instead of reading. That exact name was written
 * into a stylesheet during this session and `check:tokens` caught it, which is
 * where the mutation list comes from.
 */
const plausible = (name, real) => {
  const suffixes = ['-subtle', '-strong', '-muted', '-hover', '-inverse']
  for (const suffix of suffixes) {
    const candidate = `${name}${suffix}`
    if (!real.has(candidate)) {
      return candidate
    }
  }
  return null
}

const questions = []
let id = 0
const ask = (kind, prompt, answer, extra = {}) => {
  id += 1
  questions.push({ answer, id: `${kind}-${id}`, kind, prompt, ...extra })
}

const all = families()
const real = new Set(tokens())

/* **Aliases, and only the ones that name one family.** `Option` is an alias of
   `Toggle` and also a family of its own, so asking what `Option` is has two
   defensible answers and would score a correct agent wrong. Ambiguity is a
   property of the corpus rather than of the answer, so it is removed here. */
const claimed = new Map()
for (const entry of all) {
  for (const alias of entry.aliases) {
    claimed.set(alias.toLowerCase(), (claimed.get(alias.toLowerCase()) ?? 0) + 1)
  }
}
const names = new Set(all.map((entry) => entry.family))
for (const entry of all) {
  for (const alias of entry.aliases) {
    const key = alias.toLowerCase()
    if (claimed.get(key) !== 1 || names.has(key)) {
      continue
    }
    ask('alias', `Which Helix component family is also known as "${alias}"?`, entry.family, {
      tag: entry.tag,
    })
  }
}

/* **An example's own description, which is the retrieval task an agent actually
   faces.** A reader says what they are trying to build and the useful answer is
   a working example rather than a paragraph, so the question is the description
   and the answer is the family and slug that carry it. Descriptions unique
   across the corpus only, for the reason the aliases are deduped. */
const described = new Map()
for (const entry of all) {
  for (const example of entry.examples) {
    if (!example.description) {
      continue
    }
    const key = example.description.trim().toLowerCase()
    described.set(key, (described.get(key) ?? 0) + 1)
  }
}
for (const entry of all) {
  for (const example of entry.examples) {
    if (!example.description || described.get(example.description.trim().toLowerCase()) !== 1) {
      continue
    }
    ask(
      'example',
      `Which Helix example shows this? "${example.description}"`,
      `${entry.family}/${example.slug}`,
      { tag: entry.tag },
    )
  }
}

/* **Tokens both ways, and the negatives are the point.** An agent that answers
   yes to everything scores full marks on a corpus of real names, and the failure
   this is written for is a confident invention. */
for (const name of real) {
  ask('token', `Is \`${name}\` a token that @fusion.dev/helix-styles declares?`, 'yes')
  const wrong = plausible(name, real)
  if (wrong) {
    ask('token', `Is \`${wrong}\` a token that @fusion.dev/helix-styles declares?`, 'no')
  }
}

/* Parts, both ways, from the same manifest the reference page renders. A
   `::part()` naming something unrendered is valid CSS that matches nothing, so
   an agent guessing here produces a rule that silently does nothing. */
for (const entry of all) {
  const published = new Set(entry.parts)
  for (const part of entry.parts) {
    ask('part', `Does \`${entry.tag}\` publish a CSS part named \`${part}\`?`, 'yes', {
      tag: entry.tag,
    })
  }
  for (const invented of ['wrapper', 'inner', 'container', 'root']) {
    if (!published.has(invented)) {
      ask('part', `Does \`${entry.tag}\` publish a CSS part named \`${invented}\`?`, 'no', {
        tag: entry.tag,
      })
      break
    }
  }
}

/* Every question is answerable from something in this repository, and this is
   the list of what. Recorded so a reader can see the corpus has no hand-written
   ground truth in it at all. */
const sources = ['helix/styled/custom-elements.json', 'helix/styles/tokens.json'].filter((path) =>
  existsSync(join(ROOT, path)),
)

/* **The guard the corpus cannot supply for itself.** A family name is derived
   from a path, and a wrong derivation shared by the generator and the reference
   scores a perfect hundred while every answer is wrong: that happened, and
   `item` was the answer to twelve questions. So the names are held against the
   directories, which is the same test `check:examples` uses. */
const directories = new Set(
  readdirSync(join(ROOT, 'helix', 'styled', 'src'), { withFileTypes: true })
    .filter(
      (entry) =>
        entry.isDirectory() &&
        existsSync(join(ROOT, 'helix', 'styled', 'src', entry.name, 'index.ts')),
    )
    .map((entry) => entry.name),
)
const invented = [
  ...new Set(
    questions
      .filter((question) => question.kind === 'alias' || question.kind === 'example')
      .map((question) => String(question.answer).split('/')[0])
      .filter((name) => !directories.has(name)),
  ),
]
if (invented.length > 0) {
  console.error(
    `The corpus names ${invented.length} things that are not families under helix/styled/src: ${invented.join(', ')}.\nA family is a directory with an index.ts, and an answer that is not one is a derivation bug rather than a hard question.`,
  )
  process.exit(1)
}

const corpus = {
  /* Counted here rather than derived by a reader, and asserted by `check:eval`:
     a corpus that shrinks because a generator stopped finding something is the
     failure this number catches. */
  counts: Object.fromEntries(
    ['alias', 'example', 'part', 'token'].map((kind) => [
      kind,
      questions.filter((question) => question.kind === kind).length,
    ]),
  ),
  questions,
  sources,
  total: questions.length,
}

const wanted = `${JSON.stringify(corpus, null, 2)}\n`
if (process.argv.includes('--check')) {
  const found = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
  if (found !== wanted) {
    console.error(
      'tooling/eval/questions.json is behind the artifacts it is generated from. Run `bun run eval:build` and commit the result.',
    )
    process.exit(1)
  }
  console.log(`eval corpus: ${corpus.total} questions, current with ${sources.length} artifacts`)
} else {
  writeFileSync(OUT, wanted)
  console.log(
    `eval corpus: ${corpus.total} questions (${Object.entries(corpus.counts)
      .map(([kind, count]) => `${count} ${kind}`)
      .join(', ')})`,
  )
}
