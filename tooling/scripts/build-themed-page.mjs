#!/usr/bin/env bun
/**
 * Renders the theme builder's preview page to strings the browser never has to
 * produce.
 *
 * **The builder used to read it back out of the DOM, and that lost half of it.**
 * `<ThemedPage />` was rendered into a hidden holder and taken as `innerHTML`,
 * which works on a cold load and silently fails on a client navigation. React
 * assigns to an element's *property* when one exists and writes an attribute
 * only when it does not, and on a soft navigation the Helix definitions are
 * already registered: `command` and `name` are declared properties, Lit
 * reflects neither, and `innerHTML` cannot see a property. Measured on one
 * button, a cold load serialised `arrow-right` twice and a navigation zero
 * times, and the hero's trigger reached the frame as
 * `<helix-button commandfor="walkthrough">` with no `command` at all: a missing
 * arrow and a dialog that did nothing.
 *
 * **The obvious fix is barred, which is why this is a script.** Rendering it in
 * the server component with `renderToStaticMarkup` is the right shape and Next
 * refuses it: server components resolve under the `react-server` condition and
 * `react-dom/server` is not exported there. So the render happens here, once
 * per context, outside the app, and the app imports strings.
 *
 * Which is also the honest description of what that page is. It is never
 * rendered by React anywhere; it exists to be posted into a sandboxed frame as
 * text. Generated rather than hand-written so the JSX stays the source, and
 * held by `--check` so the two cannot drift, the same arrangement
 * `build-catalog.mjs` and `build-reference.mjs` already have.
 *
 * **One string per layout and context, which is the whole cost.** Nine
 * renderings, and they are far from nine times one page: a minimal layout is a
 * third the markup of the marketing one, and the three contexts of any layout
 * are the same structure with different words in it. Both of those make the
 * cost sublinear on the wire, and the numbers are in the run's own output
 * rather than in this comment, which is where a measurement belongs when it
 * changes every time somebody edits the copy.
 *
 * The alternative to pre-rendering is substituting the words in the frame,
 * which means a shipped component learning about this tool's data, and that is
 * a worse trade than the bytes.
 *
 * The labels travel with the markup for the same reason the markup is generated
 * at all: the builder is a client component, so importing `themed-page.tsx` to
 * read a label would pull three unrendered pages into the browser bundle. What
 * crosses is two short lists and a record of strings.
 */
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { renderToStaticMarkup } from 'react-dom/server'
import { CONTEXTS } from '../../site/ui/app/(tool)/helix/theme/themed-contexts.tsx'
import { LAYOUTS } from '../../site/ui/app/(tool)/helix/theme/themed-page.tsx'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const OUT = join(ROOT, 'site/ui/app/(tool)/helix/theme/themed-page-markup.generated.ts')

/* Keyed by the pair, because the two axes are independent and the builder holds
   one piece of state for each. A nested record would make the lookup two steps
   and buy nothing: nothing ever wants every context of one layout. */
const rendered = {}
for (const layout of LAYOUTS) {
  for (const context of CONTEXTS) {
    rendered[`${layout.value}:${context.value}`] = renderToStaticMarkup(layout.render(context))
  }
}

/* **Sorted here, because the formatter this script runs will not do it.** Keys
   come out in layout-major order, which is the order a reader would write the
   loops in and is not alphabetical, and `useSortedKeys` is an assist action:
   `biome format --write`, which is what this runs, leaves it alone while
   `biome check --write` fixes it. So the file passed or failed `biome ci`
   depending on whether somebody had run `check` over the directory since the
   last generation, which is a build that disagrees with itself. Emitting in the
   order the linter wants settles it at the source. */
const markup = Object.fromEntries(Object.entries(rendered).sort(([a], [b]) => a.localeCompare(b)))

const list = (entries) => entries.map(({ label, value }) => ({ label, value }))

const file = `/** Generated by \`bun run gen:themed-page\`. Do not edit: edit \`themed-page.tsx\`. */
export const THEMED_CONTEXTS: readonly { label: string; value: string }[] = ${JSON.stringify(list(CONTEXTS), null, 2)}

export const THEMED_LAYOUTS: readonly { label: string; value: string }[] = ${JSON.stringify(list(LAYOUTS), null, 2)}

export const THEMED_MARKUP: Readonly<Record<string, string>> = ${JSON.stringify(markup, null, 2)}
`

const pairs = Object.keys(markup)
const size = pairs.reduce((total, key) => total + markup[key].length, 0)

/* **Compared as values, written as a formatted file.**
 *
 * The check imports the module and compares the strings, rather than the file
 * byte for byte: a textual comparison would fail the moment the formatter
 * chose a different quote or wrapped the assignment, which says nothing about
 * whether the markup is current. And the writer formats what it wrote, because
 * `CLAUDE.md` asks a generator to, or every run dirties a file `check` has just
 * cleaned. */
const say = (state) =>
  `themed page: ${LAYOUTS.length} layouts by ${CONTEXTS.length} contexts, ${size} characters, ${state}`

if (process.argv.includes('--check')) {
  const held = await import(OUT)
  const same = (a, b) => JSON.stringify(a) === JSON.stringify(b)
  const stale =
    !same(held.THEMED_CONTEXTS, list(CONTEXTS)) ||
    !same(held.THEMED_LAYOUTS, list(LAYOUTS)) ||
    !same(held.THEMED_MARKUP, markup)

  if (stale) {
    console.error(
      'themed-page-markup.generated.ts is behind `themed-page.tsx` or `themed-contexts.tsx`. Run `bun run gen:themed-page` and commit the result.',
    )
    process.exit(1)
  }
  console.log(say('current'))
} else {
  writeFileSync(OUT, file)
  execFileSync('bunx', ['biome', 'format', '--write', OUT], { stdio: 'ignore' })
  console.log(say('written'))
}
