#!/usr/bin/env node
/**
 * Writes each package's tag-to-events map, from its own manifest.
 *
 * The React prop audit in `helix/core` warns about a handler prop attached to
 * nothing. It knew every event name the library has and not which element sends
 * which, so a real name on the wrong element passed silently: the mistake you
 * make while writing a *correct* event, and the one that cost a session on
 * 25 Aug 2026.
 *
 * The manifest already knows. `@event` is declared per component and
 * `check:events` holds those declarations and the dispatches together in both
 * directions, so a generated map is a third reading of a pair that is already
 * kept honest rather than a new claim.
 *
 * **Generated per package and registered on import**, because `core` sits below
 * the packages that define elements and cannot name them. Whoever is loaded
 * fills the map, so a consumer importing one component is checked against that
 * component and nothing else.
 *
 * `--check` compares without writing, for `verify`.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const PACKAGES = ['headless', 'styled']
const checking = process.argv.includes('--check')

const mapFor = (pkg) => {
  const manifest = JSON.parse(
    readFileSync(join(ROOT, 'helix', pkg, 'custom-elements.json'), 'utf8'),
  )
  const entries = []
  for (const unit of manifest.modules ?? []) {
    for (const declaration of unit.declarations ?? []) {
      const tag = declaration.tagName
      const names = (declaration.events ?? []).map((event) => event.name).filter(Boolean)
      if (tag && names.length > 0) {
        entries.push([tag, [...new Set(names)].sort()])
      }
    }
  }
  return entries.sort(([a], [b]) => a.localeCompare(b))
}

const render = (pkg, entries) => {
  const rows = entries
    .map(([tag, names]) => `  '${tag}': [${names.map((name) => `'${name}'`).join(', ')}],`)
    .join('\n')
  return `/* Generated by \`bun run element-events\` from this package's manifest. Do not edit.
 *
 * Which events each tag dispatches, registered so the React prop audit can tell
 * a handler on the wrong element from one on the right one. See
 * \`helix/core/src/events/element-events.ts\`. */
import { registerElementEvents } from '@helix-io/core'

registerElementEvents({
${rows}
})
`
}

let stale = 0
let total = 0
for (const pkg of PACKAGES) {
  const entries = mapFor(pkg)
  total += entries.length
  const path = join(ROOT, 'helix', pkg, 'src', 'element-events.generated.ts')
  const next = render(pkg, entries)
  const held = (() => {
    try {
      return readFileSync(path, 'utf8')
    } catch {
      return ''
    }
  })()
  if (held === next) {
    continue
  }
  if (checking) {
    stale += 1
    console.error(
      `helix/${pkg}/src/element-events.generated.ts is behind its manifest. Run \`bun run element-events\` and commit the result.`,
    )
    continue
  }
  writeFileSync(path, next)
}

if (stale > 0) {
  process.exit(1)
}
console.log(
  `element events: ${total} tags across ${PACKAGES.length} packages, ${checking ? 'current' : 'written'}`,
)
