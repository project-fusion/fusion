import { describe, expect, test } from 'bun:test'
import { readModule } from './native-module'

/**
 * A module as `helix family components` writes it, cut down to one of each
 * thing the reader sorts: a prop with and without a default, a prop that also
 * takes nodes, a region, and an event with a detail, with a target, with
 * both, and with neither. The form carries a comment opener and an unclosed
 * bracket in a string, which are not code.
 */
const MODULE = `/* Generated by \`helix family components\` from the intermediate forms in
   helix/neutral/src/families/tabs, the styled manifest, and the event
   details in helix/core/src/events. Do not edit: change those and run it
   again. */
import type { ComponentType, ReactNode } from 'react'
import { behaviorFor, element, type Family, type HelixEvent } from '@fusion.dev/helix-native'

export type { HelixEvent }

/** The intermediate form of \`helix-tabs\`, as \`helix family build\` writes it. */
const rootForm: Family = {"note":"a /* and a { in a string","tag":"helix-tabs"}

/** The intermediate form of \`helix-tab\`, as \`helix family build\` writes it. */
const tabForm: Family = {"tag":"helix-tab"}

/**
 * What \`onActivate\` receives: the web's \`helix-activate\`, with the fields of its
 * detail that a phone sends.
 */
export type HelixTabsActivateEvent = HelixEvent<{
  /** The value that was current before the move, where the set knows it. */
  readonly previous?: string
  /** The value after the change. */
  readonly value: string
}>

/**
 * What \`onBeforeSelect\` receives: the web's \`helix-before-select\`, with the fields of its
 * detail that a phone sends.
 */
export type HelixTabsBeforeSelectEvent = HelixEvent<
  {
    /**
     * Value of the item the reader chose, which a \`{ value }\` names, as in
     * \`a => b\`.
     */
    readonly value: string
  },
  { readonly value: string }
>

/** What \`onLoad\` receives: the web's \`helix-load\`, which carries no detail. */
export type HelixTabLoadEvent = HelixEvent<Record<never, never>, { readonly value: string }>

/** What \`onClose\` receives: the web's \`helix-close\`, which carries no detail. */
export type HelixTabCloseEvent = HelixEvent<Record<never, never>>

/**
 * The hooks \`HelixTabs\` takes in \`hooks\`. Each public hook of \`helix-tabs\` that its
 * rules read on a phone is a field named for the hook in camel case.
 */
export type HelixTabsHooks = {
  /**
   * Gap between the tabs.
   *
   * Sets \`--tabs-gap\`.
   */
  readonly gap?: number | string
}

/**
 * What \`HelixTabs\` takes. Each property of \`helix-tabs\` is a prop of the same name
 * in camel case, each slot is a prop, and each event is a handler.
 */
export type HelixTabsProps = {
  /** The tabs, as direct children of this element. */
  readonly children?: ReactNode
  /** Hooks set on the element, by each hook's name in camel case. */
  readonly hooks?: HelixTabsHooks
  /**
   * The tab list's name, read by screen readers.
   *
   * @default 'Tabs'
   */
  readonly label?: string
  /**
   * Marks the set as busy.
   *
   * Content drawn while \`loading\` is set, which ends a comment as *\\/ does.
   *
   * @default false
   */
  readonly loading?: boolean | ReactNode
  /** Fired after the active tab changes. */
  readonly onActivate?: (event: HelixTabsActivateEvent) => void
  /** Fired when a tab is chosen. */
  readonly onBeforeSelect?: (event: HelixTabsBeforeSelectEvent) => void
  /** The direction the tabs run. */
  readonly orientation?: 'horizontal' | 'vertical'
}

/**
 * A row of tabs and the panel each one shows.
 *
 * \`helix-tabs\` drawn natively from its intermediate form.
 */
export const HelixTabs = element(rootForm, behaviorFor(rootForm)) as ComponentType<HelixTabsProps>

/** The hooks \`HelixTab\` takes in \`hooks\`. */
export type HelixTabHooks = Record<never, never>

/**
 * What \`HelixTab\` takes. Each property of \`helix-tab\` is a prop of the same name
 * in camel case, each slot is a prop, and each event is a handler.
 */
export type HelixTabProps = {
  /** Fired when the tab asks to close. */
  readonly onClose?: (event: HelixTabCloseEvent) => void
  /** Fired the first time a panel is shown. */
  readonly onLoad?: (event: HelixTabLoadEvent) => void
}

/**
 * One tab in a tab list.
 *
 * \`helix-tab\` drawn natively from its intermediate form.
 */
export const HelixTab = element(tabForm, behaviorFor(tabForm)) as ComponentType<HelixTabProps>
`

/** The target's field, where the element that sent the event has a value. */
const VALUE = { description: '', name: 'value', optional: false, type: 'string' }

describe('a native module', () => {
  const { components, runtime } = readModule(MODULE, 'tabs')
  const [tabs, tab] = components

  test('declares its components in its own order, each with its element and summary', () => {
    expect(components.map((one) => [one.name, one.tag])).toEqual([
      ['HelixTabs', 'helix-tabs'],
      ['HelixTab', 'helix-tab'],
    ])
    expect(tabs?.summary).toBe('A row of tabs and the panel each one shows.')
    expect(runtime).toBe('@fusion.dev/helix-native')
  })

  test('gives each prop its type, and its default where it has one', () => {
    expect(tabs?.props).toEqual([
      {
        description: "Hooks set on the element, by each hook's name in camel case.",
        name: 'hooks',
        type: 'HelixTabsHooks',
      },
      {
        default: "'Tabs'",
        description: "The tab list's name, read by screen readers.",
        name: 'label',
        type: 'string',
      },
      {
        default: 'false',
        description:
          'Marks the set as busy. Content drawn while `loading` is set, which ends a comment as */ does.',
        name: 'loading',
        type: 'boolean | ReactNode',
      },
      {
        description: 'The direction the tabs run.',
        name: 'orientation',
        type: "'horizontal' | 'vertical'",
      },
    ])
  })

  test('gives each component the fields of its hooks type, and none for an empty one', () => {
    expect(tabs?.hooks).toEqual([
      {
        description: 'Gap between the tabs. Sets `--tabs-gap`.',
        name: 'gap',
        optional: true,
        type: 'number | string',
      },
    ])
    expect(tab?.hooks).toEqual([])
  })

  test('puts a prop that takes nodes alone among the regions', () => {
    expect(tabs?.regions).toEqual([
      { description: 'The tabs, as direct children of this element.', name: 'children' },
    ])
  })

  test('gives each handler the fields of its detail', () => {
    const activate = tabs?.events.find((one) => one.name === 'onActivate')
    expect(activate?.detail).toEqual([
      {
        description: 'The value that was current before the move, where the set knows it.',
        name: 'previous',
        optional: true,
        type: 'string',
      },
      {
        description: 'The value after the change.',
        name: 'value',
        optional: false,
        type: 'string',
      },
    ])
    expect(activate?.target).toEqual([])
  })

  test('reads a platform event as an event, with the fields of its detail', () => {
    const { components: read } = readModule(
      MODULE.replace(
        'export type HelixTabsActivateEvent = HelixEvent<{',
        'export type HelixTabsActivateEvent = PlatformEvent<{',
      ),
      'tabs',
    )
    const activate = read[0]?.events.find((one) => one.name === 'onActivate')
    expect(activate?.detail.map((field) => field.name)).toEqual(['previous', 'value'])
  })

  test('says where the target carries a value, with a detail or without one', () => {
    const select = tabs?.events.find((one) => one.name === 'onBeforeSelect')
    expect(select?.detail.map((field) => field.name)).toEqual(['value'])
    expect(select?.detail[0]?.description).toBe(
      'Value of the item the reader chose, which a `{ value }` names, as in `a => b`.',
    )
    expect(select?.target).toEqual([VALUE])
    expect(tab?.events).toEqual([
      {
        description: 'Fired when the tab asks to close.',
        detail: [],
        name: 'onClose',
        target: [],
      },
      {
        description: 'Fired the first time a panel is shown.',
        detail: [],
        name: 'onLoad',
        target: [VALUE],
      },
    ])
  })

  test('refuses a line it does not recognize, naming the module', () => {
    const changed = MODULE.replace('readonly orientation?:', 'orientation?:')
    expect(() => readModule(changed, 'tabs')).toThrow('tabs: cannot read the member')
  })

  test('refuses a handler whose event type is missing', () => {
    const changed = MODULE.replace(
      'export type HelixTabLoadEvent',
      'export type HelixTabLoadedEvent',
    )
    expect(() => readModule(changed, 'tabs')).toThrow('hears `HelixTabLoadEvent`')
  })
})
